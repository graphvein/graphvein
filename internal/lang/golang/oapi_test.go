package golang

import (
	"os"
	"strings"
	"testing"

	"github.com/graphvein/graphvein/internal/lang/facts"
)

// oapiFixture reads a generated server of the go-routes fixture.
func oapiFixture(t *testing.T, name string) string {
	t.Helper()
	data, err := os.ReadFile("../../../testdata/fixtures/go-routes/oapi/" + name)
	if err != nil {
		t.Fatal(err)
	}
	return string(data)
}

// TestGoGeneratedServer checks row RO-server against the go-routes
// fixture's hand-written servers (chi, gin and net/http, in the shape of
// oapi-codegen v2.8.x) and row RO-D against edits of them: the payload is
// set only when the header and every server declaration match the
// templates token for token.
func TestGoGeneratedServer(t *testing.T) {
	chi := oapiFixture(t, "petchi/petchi.gen.go")
	gin := oapiFixture(t, "petgin/petgin.gen.go")
	std := oapiFixture(t, "petstd/petstd.gen.go")
	cases := []struct {
		name, source string
		want         *facts.GoGenerated
	}{
		{"chi", chi, &facts.GoGenerated{Generator: "oapi-codegen", Version: "v2.8.0", Framework: "chi"}},
		{"gin", gin, &facts.GoGenerated{Generator: "oapi-codegen", Version: "v2.8.2", Framework: "gin"}},
		{"net/http", std, &facts.GoGenerated{Generator: "oapi-codegen", Version: "v2.8.1", Framework: "net/http"}},
		{"reformatted", strings.ReplaceAll(chi, "\t", "  "), &facts.GoGenerated{Generator: "oapi-codegen", Version: "v2.8.0", Framework: "chi"}},
		{"older version", strings.Replace(chi, "version v2.8.0", "version v2.7.2", 1), nil},
		{"no header", strings.Replace(chi, "// Code generated by", "// Written by", 1), nil},
		{"header after the package clause", strings.Replace(strings.Replace(chi, "// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.8.0 DO NOT EDIT.\n", "", 1), "package petchi\n", "package petchi\n\n// Code generated by github.com/oapi-codegen/oapi-codegen/v2 version v2.8.0 DO NOT EDIT.\n", 1), nil},
		{"registration without BaseURL", strings.Replace(chi, `r.Get(options.BaseURL+"/pets", wrapper.ListPets)`, `r.Get("/pets", wrapper.ListPets)`, 1), nil},
		{"method no router declares", strings.Replace(chi, `r.Get(options.BaseURL+"/pets", wrapper.ListPets)`, `r.Query(options.BaseURL+"/pets", wrapper.ListPets)`, 1), nil},
		{"extra statement", strings.Replace(chi, "\n\treturn r\n}", "\n\tr.Use(nil)\n\n\treturn r\n}", 1), nil},
		{"BaseRouter ignored", strings.Replace(chi, "\tr := options.BaseRouter\n", "\tr := chi.Router(nil)\n", 1), nil},
		{"wrapper calls another method", strings.Replace(chi, "siw.Handler.ListPets(w, r)", "siw.Handler.ShowPetById(w, r, \"\")", 1), nil},
		{"wrapper calls twice", strings.Replace(chi, "siw.Handler.ListPets(w, r)\n", "siw.Handler.ListPets(w, r)\n\t\tsiw.Handler.ListPets(w, r)\n", 1), nil},
		{"wrapper method missing", strings.Replace(chi, "func (siw *ServerInterfaceWrapper) ListPets(", "func (siw *ServerInterfaceWrapper) ListAll(", 1), nil},
		{"gin route through another router", strings.Replace(gin, `router.GET(options.BaseURL+"/pets", wrapper.ListPets)`, `gin.Default().GET(options.BaseURL+"/pets", wrapper.ListPets)`, 1), nil},
		{"net/http pattern without method", strings.Replace(std, `m.HandleFunc(http.MethodGet+" "+options.BaseURL+"/pets", wrapper.ListPets)`, `m.HandleFunc(options.BaseURL+"/pets", wrapper.ListPets)`, 1), nil},
		{"net/http method literal", strings.Replace(std, `m.HandleFunc(http.MethodGet+" "+options.BaseURL+"/pets", wrapper.ListPets)`, `m.HandleFunc("QUERY"+" "+options.BaseURL+"/pets", wrapper.ListPets)`, 1), &facts.GoGenerated{Generator: "oapi-codegen", Version: "v2.8.1", Framework: "net/http"}},
		{"aliased chi import", strings.Replace(chi, "\t\"github.com/go-chi/chi/v5\"", "\tchi \"github.com/go-chi/chi/v5\"", 1), nil},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			f := parseGo(t, "api/api.gen.go", c.source)
			var got *facts.GoGenerated
			if f.Go.Routes != nil {
				got = f.Go.Routes.Generated
			}
			if (got == nil) != (c.want == nil) || got != nil && *got != *c.want {
				t.Errorf("generated = %+v, want %+v", got, c.want)
			}
		})
	}
}
