// This file recognises the HTTP servers oapi-codegen generates (task T023,
// developer decision GO2; docs/lang/go-routes.md, rows RO-*). A
// file is a generated server when its header names an oapi-codegen version
// whose templates were read (oapiVersions) and the server declarations
// match those templates token for token: the entry functions (Handler,
// HandlerFromMux, HandlerFromMuxWithBaseURL and HandlerWithOptions of the
// chi-server and std-http-server outputs, RegisterHandlers and
// RegisterHandlersWithOptions of the gin-server output), the options
// struct, the ServerInterfaceWrapper struct and, for every registration,
// the wrapper method that calls the ServerInterface method of the same
// name. The payload records only that the shape matched (syntax, rule 31):
// which router the routes register on, the BaseURL they are registered
// under and which type implements ServerInterface are decided at link time
// from the calls of the entry functions (contract row GR-G1).
//
// The templates are oapi-codegen v2.8.0's pkg/codegen/templates (Apache
// License 2.0): chi/chi-handler.tmpl, chi/chi-middleware.tmpl,
// gin/gin-register.tmpl, gin/gin-wrappers.tmpl,
// stdhttp/std-http-handler.tmpl and stdhttp/std-http-middleware.tmpl, with
// the path helpers SwaggerUriToChiUri, SwaggerUriToGinUri and
// SwaggerUriToStdHttpUri of pkg/codegen/utils.go. v2.8.1 and v2.8.2 have
// the same files byte for byte; v2.7.2 and earlier differ.

// oapiVersions are the oapi-codegen versions whose server templates equal
// the templates read (see above).
var oapiVersions = map[string]bool{"v2.8.0": true, "v2.8.1": true, "v2.8.2": true}

// oapiHeader is the generated-file line of imports.tmpl ("Code generated by
// {{.ModuleName}} version {{.Version}} DO NOT EDIT.").
var oapiHeader = regexp.MustCompile(`^// Code generated by github\.com/oapi-codegen/oapi-codegen/v2 version (v[0-9]+\.[0-9]+\.[0-9]+) DO NOT EDIT\.$`)

// OapiEntries are the entry functions of a generated server: a call of one
// is an instance of the server (contract row GR-G1). A file that calls one
// passes the route gate (row RG-generated).
var OapiEntries = map[string]bool{"Handler": true, "HandlerFromMux": true, "HandlerFromMuxWithBaseURL": true, "HandlerWithOptions": true, "RegisterHandlers": true, "RegisterHandlersWithOptions": true}

