// oapiChiMethods, oapiGinMethods: the registration method names of the
// templates' method calls that chi v5 and gin v1 declare (the template
// writes the operation's method title-cased for chi, upper-case for gin;
// another method, such as QUERY, names no router method).
var (
	oapiChiMethods = map[string]bool{"Get": true, "Post": true, "Put": true, "Patch": true, "Delete": true, "Head": true, "Options": true, "Connect": true, "Trace": true}
	oapiGinMethods = map[string]bool{"GET": true, "POST": true, "PUT": true, "PATCH": true, "DELETE": true, "HEAD": true, "OPTIONS": true}
)

// oapiTok is one token: the token kind and, for identifiers and literals,
// the text. Automatic and explicit semicolons are one kind.
type oapiTok struct {
	tok token.Token
	lit string
}

// oapiTokens scans Go source into tokens, comments dropped; trailing
// semicolons are trimmed. ok is false on a scan error.
func oapiTokens(src []byte) (out []oapiTok, ok bool) {
	var s scanner.Scanner
	fset := token.NewFileSet()
	errs := 0
	s.Init(fset.AddFile("", -1, len(src)), src, func(token.Position, string) { errs++ }, 0)
	for {
		_, tok, lit := s.Scan()
		if tok == token.EOF {
			break
		}
		if tok == token.SEMICOLON || !tok.IsLiteral() {
			lit = ""
		}
		out = append(out, oapiTok{tok, lit})
	}
	for len(out) > 0 && out[len(out)-1].tok == token.SEMICOLON {
		out = out[:len(out)-1]
	}
	return out, errs == 0
}

// oapiMustTokens scans a template text.
func oapiMustTokens(text string) []oapiTok {
	out, ok := oapiTokens([]byte(text))
	if !ok {
		panic("oapi template does not scan: " + text)
	}
	return out
}

// oapiMatch matches the template text at got[i:]: it returns the position
// after the match and the identifiers and string literals the GVID and
// GVSTR placeholders matched, in order.
func oapiMatch(got []oapiTok, i int, text string) (next int, captures []string, ok bool) {
	want := oapiMustTokens(text)
	for _, w := range want {
		if i >= len(got) {
			return 0, nil, false
		}
		g := got[i]
		switch {
		case w.tok == token.IDENT && w.lit == "GVID":
			if g.tok != token.IDENT {
				return 0, nil, false
			}
			captures = append(captures, g.lit)
		case w.tok == token.IDENT && w.lit == "GVSTR":
			if g.tok != token.STRING {
				return 0, nil, false
			}
			captures = append(captures, g.lit)
		case w != g:
			return 0, nil, false
		}
		i++
	}
	return i, captures, true
}

// oapiSkipSemis skips semicolons at got[i:].
func oapiSkipSemis(got []oapiTok, i int) int {
	for i < len(got) && got[i].tok == token.SEMICOLON {
		i++
	}
	return i
}

// oapiSeq matches a sequence of template texts, separated by semicolons,
// that must cover got exactly.
func oapiSeq(got []oapiTok, texts ...string) bool {
	i := 0
	for _, t := range texts {
		var ok bool
		if i, _, ok = oapiMatch(got, oapiSkipSemis(got, i), t); !ok {
			return false
		}
	}
	return oapiSkipSemis(got, i) == len(got)
}

// oapiDecls are a parsed file's top-level declarations by name: functions,
// ServerInterfaceWrapper methods and type declarations of one spec, each
// as its source tokens; a name declared twice is dropped.
type oapiDecls struct {
	funcs, methods, types map[string][]oapiTok
}

func oapiCollect(src []byte, file *ast.File, fset *token.FileSet) (*oapiDecls, bool) {
	d := &oapiDecls{funcs: map[string][]oapiTok{}, methods: map[string][]oapiTok{}, types: map[string][]oapiTok{}}
	dup := map[string]bool{}
	add := func(m map[string][]oapiTok, kind, name string, n ast.Node) bool {
		from, to := fset.Position(n.Pos()).Offset, fset.Position(n.End()).Offset
		if from < 0 || to > len(src) || from > to {
			return false
		}
		toks, ok := oapiTokens(src[from:to])
		if !ok {
			return false
		}
		if _, seen := m[name]; seen || dup[kind+name] {
			dup[kind+name] = true
			delete(m, name)
			return true
		}
		m[name] = toks
		return true
	}
	for _, decl := range file.Decls {
		switch x := decl.(type) {
		case *ast.FuncDecl:
			if x.Recv == nil {
				if !add(d.funcs, "f", x.Name.Name, x) {
					return nil, false
				}
				continue
			}
			if len(x.Recv.List) == 1 {
				if star, ok := x.Recv.List[0].Type.(*ast.StarExpr); ok {
					if id, ok := star.X.(*ast.Ident); ok && id.Name == "ServerInterfaceWrapper" {
						if !add(d.methods, "m", x.Name.Name, x) {
							return nil, false
						}
					}
				}
			}
		case *ast.GenDecl:
			if x.Tok != token.TYPE || len(x.Specs) != 1 || x.Lparen.IsValid() {
				continue
			}
			if !add(d.types, "t", x.Specs[0].(*ast.TypeSpec).Name.Name, x) {
				return nil, false
			}
		}
	}
	return d, true
}

// generatedServer returns the generated-server payload of a file (row
// RO-server), nil when its header names no read oapi-codegen version or
// its server declarations differ from the templates (row RO-D).
func generatedServer(source []byte, imports []facts.Import) *facts.GoGenerated {
	version := ""
	for _, line := range strings.Split(string(source), "\n") {
		line = strings.TrimRight(line, "\r")
		if strings.HasPrefix(line, "package ") {
			break
		}
		if m := oapiHeader.FindStringSubmatch(line); m != nil {
			version = m[1]
			break
		}
	}
	if version == "" {
		return nil
	}
	if !oapiVersions[version] {
		tagRoute("RO-D", version)
		return nil
	}
	framework := oapiFramework(imports)
	if framework == "" {
		tagRoute("RO-D", "imports")
		return nil
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "", source, parser.SkipObjectResolution)
	if err != nil {
		tagRoute("RO-D", "parse")
		return nil
	}
	decls, ok := oapiCollect(source, file, fset)
	if !ok || !oapiShape(decls, framework) {
		tagRoute("RO-D", framework)
		return nil
	}
	g := &facts.GoGenerated{Generator: "oapi-codegen", Version: version, Framework: framework}
	tagRoute("RO-server", *g)
	return g
}

// oapiFramework is the server variant a generated file's imports allow:
// net/http unaliased, and chi v5 or gin unaliased (chi-server, gin-server)
// or neither (std-http-server), as imports.tmpl writes them.
func oapiFramework(imports []facts.Import) string {
	plain := map[string]bool{}
	for _, imp := range imports {
		if imp.ExplicitAlias {
			return ""
		}
		plain[imp.Module] = true
	}
	chi, gin := plain["github.com/go-chi/chi/v5"], plain["github.com/gin-gonic/gin"]
	switch {
	case !plain["net/http"] || chi && gin:
		return ""
	case chi:
		return "chi"
	case gin:
		return "gin"
	}
	return "net/http"
}

// oapiShape checks a generated file's server declarations against the
// templates of its variant.
func oapiShape(d *oapiDecls, framework string) bool {
	switch framework {
	case "chi":
		if !oapiSeq(d.funcs["Handler"], oapiChiHandler) || !oapiSeq(d.types["ChiServerOptions"], oapiChiOptions) ||
			!oapiSeq(d.funcs["HandlerFromMux"], oapiChiFromMux) || !oapiSeq(d.funcs["HandlerFromMuxWithBaseURL"], oapiChiFromMuxBase) {
			return false
		}
		handlers, ok := oapiRegistrations(d.funcs["HandlerWithOptions"], oapiChiWithOptions, oapiHTTPWrapper, oapiChiGroup, oapiChiReturn, oapiChiMethods)
		return ok && oapiWrappers(d, handlers, oapiHTTPWrapperType, oapiHTTPMethod, "w", "r")
	case "net/http":
		if !oapiSeq(d.funcs["Handler"], oapiStdHandler) || !oapiSeq(d.types["ServeMux"], oapiStdServeMux) || !oapiSeq(d.types["StdHTTPServerOptions"], oapiStdOptions) ||
			!oapiSeq(d.funcs["HandlerFromMux"], oapiStdFromMux) || !oapiSeq(d.funcs["HandlerFromMuxWithBaseURL"], oapiStdFromMuxBase) {
			return false
		}
		handlers, ok := oapiStdRegistrations(d.funcs["HandlerWithOptions"])
		return ok && oapiWrappers(d, handlers, oapiHTTPWrapperType, oapiHTTPMethod, "w", "r")
	case "gin":
		if !oapiSeq(d.types["GinServerOptions"], oapiGinOptions) || !oapiSeq(d.funcs["RegisterHandlers"], oapiGinRegister) {
			return false
		}
		handlers, ok := oapiRegistrations(d.funcs["RegisterHandlersWithOptions"], oapiGinWithOptions, oapiGinPrefix, oapiGinRoute, oapiEnd, oapiGinMethods)
		return ok && oapiWrappers(d, handlers, oapiGinWrapperType, oapiGinMethod, "c")
	}
	return false
}

// oapiRegistrations matches a registering function: head, then (when it
// registers anything) the wrapper binding and one registration per
// operation, then tail. A registration's method must be one of methods;
// it returns the registrations' wrapper method names. A server without
// operations has neither the wrapper binding (with gin's error handler
// before it) nor a registration.
func oapiRegistrations(got []oapiTok, head, wrapper, route, tail string, methods map[string]bool) ([]string, bool) {
	i, _, ok := oapiMatch(got, 0, head)
	if !ok {
		return nil, false
	}
	if j, _, ok := oapiMatch(got, oapiSkipSemis(got, i), wrapper); ok {
		i = j
	} else if k, _, ok := oapiMatch(got, oapiSkipSemis(got, i), tail); !ok || oapiSkipSemis(got, k) != len(got) {
		return nil, false
	} else {
		// No operation: the template writes no wrapper and no
		// registration.
		return nil, true
	}
	var handlers []string
	for {
		j, caps, ok := oapiMatch(got, oapiSkipSemis(got, i), route)
		if !ok {
			break
		}
		if !methods[caps[0]] {
			return nil, false
		}
		handlers = append(handlers, caps[2])
		i = j
	}
	if len(handlers) == 0 {
		return nil, false
	}
	k, _, ok := oapiMatch(got, oapiSkipSemis(got, i), tail)
	if !ok || oapiSkipSemis(got, k) != len(got) {
		return nil, false
	}
	return handlers, true
}

// oapiStdRegistrations matches the std-http-server HandlerWithOptions:
// m.HandleFunc(M+" "+options.BaseURL+P, wrapper.N) with M an
// http.Method* constant or a string literal (httpMethodConstant).
func oapiStdRegistrations(got []oapiTok) ([]string, bool) {
	i, _, ok := oapiMatch(got, 0, oapiStdWithOptions)
	if !ok {
		return nil, false
	}
	j, _, ok := oapiMatch(got, oapiSkipSemis(got, i), oapiHTTPWrapper)
	if !ok {
		k, _, ok := oapiMatch(got, oapiSkipSemis(got, i), oapiStdReturn)
		return nil, ok && oapiSkipSemis(got, k) == len(got)
	}
	i = j
	var handlers []string
	for {
		start := oapiSkipSemis(got, i)
		k, c, ok := oapiMatch(got, start, `m.HandleFunc(http.GVID+" "+options.BaseURL+GVSTR, wrapper.GVID)`)
		if ok {
			if _, known := httpMethodConstants[c[0]]; !known {
				return nil, false
			}
		} else if k, c, ok = oapiMatch(got, start, `m.HandleFunc(GVSTR+" "+options.BaseURL+GVSTR, wrapper.GVID)`); !ok {
			break
		}
		handlers = append(handlers, c[2])
		i = k
	}
	if len(handlers) == 0 {
		return nil, false
	}
	k, _, ok := oapiMatch(got, oapiSkipSemis(got, i), oapiStdReturn)
	if !ok || oapiSkipSemis(got, k) != len(got) {
		return nil, false
	}
	return handlers, true
}

// httpMethodConstants are the net/http constants httpMethodConstant writes.
var httpMethodConstants = map[string]string{"MethodGet": "GET", "MethodPost": "POST", "MethodPut": "PUT", "MethodDelete": "DELETE", "MethodPatch": "PATCH", "MethodHead": "HEAD", "MethodOptions": "OPTIONS", "MethodTrace": "TRACE"}

// oapiWrappers checks the ServerInterfaceWrapper struct and, for every
// registered wrapper method N, that the method has the template's
// signature and calls siw.Handler.N(<args>...) exactly once, the only use
// of siw.Handler in its body: the registered handler serves the request
// through the ServerInterface method N of the value the entry function
// was given (contract row GR-G1's handler).
func oapiWrappers(d *oapiDecls, handlers []string, wrapperType, method string, args ...string) bool {
	if len(handlers) > 0 && !oapiSeq(d.types["ServerInterfaceWrapper"], wrapperType) {
		return false
	}
	for _, name := range handlers {
		got := d.methods[name]
		i, caps, ok := oapiMatch(got, 0, method)
		if !ok || caps[0] != name {
			return false
		}
		calls := 0
		for k := i; k+4 < len(got); k++ {
			if got[k] != (oapiTok{token.IDENT, "siw"}) || got[k+1].tok != token.PERIOD || got[k+2] != (oapiTok{token.IDENT, "Handler"}) || got[k+3].tok != token.PERIOD {
				continue
			}
			calls++
			call := "siw.Handler." + name + "(" + strings.Join(args, ", ")
			j, _, ok := oapiMatch(got, k, call)
			if !ok {
				return false
			}
			// Further arguments are identifiers (the path parameters
			// and the params object).
			for j+1 < len(got) && got[j].tok == token.COMMA && got[j+1].tok == token.IDENT {
				j += 2
			}
			if j >= len(got) || got[j].tok != token.RPAREN {
				return false
			}
		}
		if calls != 1 {
			return false
		}
	}
	return true
}
