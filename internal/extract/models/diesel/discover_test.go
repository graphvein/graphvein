const schemaRS = "// @generated automatically by Diesel CLI.\n\ndiesel::table! {\n    users (id) {\n        id -> Int4,\n    }\n}\n"

func lockWith(versions ...string) string {
	var b strings.Builder
	b.WriteString("# This file is automatically @generated by Cargo.\nversion = 4\n\n")
	for _, v := range versions {
		b.WriteString("[[package]]\nname = \"diesel\"\nversion = \"" + v + "\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\ndependencies = [\n \"diesel_derives\",\n]\n\n")
	}
	b.WriteString("[[package]]\nname = \"app\"\nversion = \"0.1.0\"\n")
	return b.String()
}

func sources(files map[string]string) map[string][]byte {
	out := map[string][]byte{}
	for k, v := range files {
		out[k] = []byte(v)
	}
	return out
}

func discover(t *testing.T, files map[string]string) (*Discovery, []contract.Diagnostic, []string) {
	t.Helper()
	var tags []string
	d, diags := Discover(Input{Sources: sources(files), Tag: func(row string) { tags = append(tags, row) }})
	return d, diags, tags
}

func messages(diags []contract.Diagnostic) []string {
	var out []string
	for _, d := range diags {
		out = append(out, d.Code+" "+d.Message)
	}
	return out
}

