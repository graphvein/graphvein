// linkPackage links one postgres package: a diesel.toml section for
// src/schema.rs, the diesel pin and the files given.
func linkPackage(t *testing.T, version string, files map[string]string) ([]contract.Node, []contract.Edge, []contract.Diagnostic) {
	t.Helper()
	all := map[string]string{
		"diesel.toml": "[print_schema]\nfile = \"src/schema.rs\"\n",
		"Cargo.toml":  "[package]\nname = \"app\"\n[dependencies]\ndiesel = { version = \"2\", features = [\"postgres\"] }\n",
		"Cargo.lock":  lockWith(version),
	}
	if version == "" {
		// No Cargo.lock: the pin is not proven (and the dialect unknown,
		// so the dialect comes from the test's own lock below).
		delete(all, "Cargo.lock")
	}
	for k, v := range files {
		all[k] = v
	}
	return Link(Input{Sources: sources(all)})
}

func attrsOf(nodes []contract.Node, id string) map[string]any {
	for _, n := range nodes {
		if n.Identity == id {
			return n.Attributes
		}
	}
	return nil
}

func claimVerification(a map[string]any, fact string) string {
	list, _ := a["claims"].([]models.Claim)
	for _, c := range list {
		if c.Fact == fact {
			return c.Verification
		}
	}
	return ""
}

// olderSchema is diesel_cli output with the line proof (unless empty)
// above users.code: "#[max_length = 9]", a database comment, or 2.0's
// generated column text.
func olderSchema(proof string) string {
	return `// @generated automatically by Diesel CLI.

diesel::table! {
    users (id) {
        id -> Int4,
        name -> Varchar,
        bits -> Varbit,
` + proof + `        code -> Varchar,
    }
}

diesel::table! {
    posts (id) {
        id -> Int4,
        user_id -> Int4,
    }
}

diesel::joinable!(posts -> users (user_id));
`
}

const (
	proofMaxLength = "        #[max_length = 9]\n"
	proofComment   = "        /// The user's short code\n"
	proofCLI20Docs = "        /// The `code` column of the `users` table.\n        ///\n        /// Its SQL type is `Varchar`.\n        ///\n        /// (Automatically generated by Diesel.)\n"
	proofDocAttr   = "        #[doc = \"The user's short code\"]\n"
)

// TestDieselOlderPins checks A1 as the Revision 2 addendum
// refines it: a file counts as diesel_cli 2.1 or later output only when it
// shows it (a #[max_length] or a database comment on a generated line),
// whatever the diesel pin. Otherwise Varchar and Varbit without
// #[max_length] are their families, no joinable! is a foreign key and the
// group lists DI-V9; a proven file lists DI-V9 only below 2.3.14.
func TestDieselOlderPins(t *testing.T) {
	for _, c := range []struct {
		version, proof     string
		family, fk, olderV bool
	}{
		{"2.0.4", "", true, false, true},
		{"2.0.4", proofMaxLength, false, true, true},
		{"2.1.0-rc.1", proofMaxLength, false, true, true},
		{"2.2.0", proofComment, false, true, true},
		{"2.3.13", proofMaxLength, false, true, true},
		{"2.3.14", proofMaxLength, false, true, false},
		{"2.3.14", proofComment, false, true, false},
		{"2.3.14", "", true, false, true},
		{"2.3.14", proofCLI20Docs, true, false, true},
		{"2.3.14", proofDocAttr, true, false, true},
		{"2.4.1", "", true, false, true},
		{"2.4.1", proofMaxLength, false, true, false},
	} {
		label := c.version + " " + strings.TrimSpace(strings.SplitN(c.proof, "\n", 2)[0])
		nodes, edges, _ := linkPackage(t, c.version, map[string]string{"src/schema.rs": olderSchema(c.proof)})
		name := attrsOf(nodes, "column:src/schema.rs#users.name")
		bits := attrsOf(nodes, "column:src/schema.rs#users.bits")
		code := attrsOf(nodes, "column:src/schema.rs#users.code")
		if name == nil || bits == nil || code == nil {
			t.Fatalf("diesel %s: columns missing", label)
		}
		gotFamily := name["type_family"] != nil && bits["type_family"] != nil
		if gotFamily != c.family || c.family && (name["type"] != nil || bits["type"] != nil) || !c.family && (name["type"] != "character varying" || bits["type"] != "bit varying") {
			t.Errorf("diesel %s: name %v/%v bits %v/%v, want family %v", label, name["type"], name["type_family"], bits["type"], bits["type_family"], c.family)
		}
		if c.proof == proofMaxLength && code["type"] != "character varying(9)" {
			t.Errorf("diesel %s: code %v", label, code["type"])
		}
		fk := false
		for _, e := range edges {
			fk = fk || e.Kind == "foreign_key" && e.Source == "column:src/schema.rs#posts.user_id"
		}
		if fk != c.fk {
			t.Errorf("diesel %s: foreign key %v, want %v", label, fk, c.fk)
		}
		if !c.fk {
			reasons := fmt.Sprint(attrsOf(nodes, "column:src/schema.rs#posts.user_id")["reasons"])
			if !strings.Contains(reasons, "no diesel_cli 2.1 or later output") {
				t.Errorf("diesel %s: reasons %s", label, reasons)
			}
		}
		list, _ := attrsOf(nodes, "table:src/schema.rs#users")["assumptions"].([]string)
		if slices.Contains(list, AssumeOlderPin) != c.olderV {
			t.Errorf("diesel %s: assumptions %v", label, list)
		}
	}
	// A pin that is not proven (no Cargo.lock) lists DI-V9 even when the
	// file shows 2.1 output.
	nodes, edges, _ := Link(Input{Sources: sources(map[string]string{
		"diesel.toml":   "[print_schema]\nfile = \"src/schema.rs\"\n",
		"Cargo.toml":    "[package]\nname = \"app\"\n[dependencies]\ndiesel = { version = \"2\", features = [\"postgres\"] }\n",
		"src/schema.rs": olderSchema(proofMaxLength),
	})})
	list, _ := attrsOf(nodes, "table:src/schema.rs#users")["assumptions"].([]string)
	if !slices.Contains(list, AssumeOlderPin) {
		t.Errorf("unproven pin: assumptions %v", list)
	}
	fk := false
	for _, e := range edges {
		fk = fk || e.Kind == "foreign_key"
	}
	if !fk {
		t.Error("unproven pin with #[max_length]: no foreign key")
	}
	if !olderThan("", "2.1.0") || !olderThan("2.x", "2.1.0") || olderThan("2.1.0", "2.1.0") || !olderThan("2.0.9", "2.1.0") {
		t.Error("olderThan")
	}
}

// TestDieselSqliteJoinable checks Revision 2 addendum 2: a SQLite file
// shows no diesel_cli 2.1 output (no lengths, no comments), yet its
// generated joinable! lines are foreign keys at any pin, since diesel_cli
// 2.0.1 and 2.1.1 write the same SQLite joinable! set.
func TestDieselSqliteJoinable(t *testing.T) {
	schema := `// @generated automatically by Diesel CLI.

diesel::table! {
    posts (id) {
        id -> Integer,
        user_id -> Integer,
    }
}

diesel::table! {
    users (id) {
        id -> Integer,
        name -> Text,
    }
}

diesel::joinable!(posts -> users (user_id));
`
	for _, version := range []string{"2.0.4", "2.3.14"} {
		nodes, edges, _ := linkPackage(t, version, map[string]string{
			"Cargo.toml":    "[package]\nname = \"app\"\n[dependencies]\ndiesel = { version = \"2\", features = [\"sqlite\"] }\n",
			"src/schema.rs": schema,
		})
		if d := attrsOf(nodes, "table:src/schema.rs#users")["dialect"]; d != "sqlite" {
			t.Fatalf("diesel %s: dialect %v", version, d)
		}
		fk := false
		for _, e := range edges {
			fk = fk || e.Kind == "foreign_key" && e.Source == "column:src/schema.rs#posts.user_id" && e.Target == "column:src/schema.rs#users.id"
		}
		if !fk {
			t.Errorf("diesel %s: no foreign key posts.user_id -> users.id", version)
		}
		list, _ := attrsOf(nodes, "table:src/schema.rs#users")["assumptions"].([]string)
		if !slices.Contains(list, AssumeOlderPin) {
			t.Errorf("diesel %s: assumptions %v, want DI-V9", version, list)
		}
	}
}

// TestDieselPatchSpans checks A3 with the two forms the review probed: a
// patch that adds #[max_length] above a generated column, and one that
// rewrites a struct's postgres_type name; and a patch-added attribute
// above a key column, which leaves the primary key unknown.
func TestDieselPatchSpans(t *testing.T) {
	orig := `// @generated automatically by Diesel CLI.

pub mod sql_types {
    #[derive(diesel::query_builder::QueryId, Clone, diesel::sql_types::SqlType)]
    #[diesel(postgres_type(name = "user_kind"))]
    pub struct MyEnum;
}

diesel::table! {
    use diesel::sql_types::*;
    use super::sql_types::MyEnum;

    users (id) {
        id -> Int4,
        name -> Varchar,
        kind -> MyEnum,
    }
}
`
	schema := strings.Replace(strings.Replace(orig, `name = "user_kind"`, `name = "my_enum"`, 1), "        name -> Varchar,", "        #[max_length = 10]\n        name -> Varchar,", 1)
	patch := `--- a/src/schema.rs
+++ b/src/schema.rs
@@ -2,7 +2,7 @@
 
 pub mod sql_types {
     #[derive(diesel::query_builder::QueryId, Clone, diesel::sql_types::SqlType)]
-    #[diesel(postgres_type(name = "user_kind"))]
+    #[diesel(postgres_type(name = "my_enum"))]
     pub struct MyEnum;
 }
 
@@ -13,6 +13,7 @@
 
     users (id) {
         id -> Int4,
+        #[max_length = 10]
         name -> Varchar,
         kind -> MyEnum,
     }
`
	nodes, _, diags := linkPackage(t, "2.3.14", map[string]string{
		"diesel.toml":      "[print_schema]\nfile = \"src/schema.rs\"\npatch_file = \"src/schema.patch\"\n",
		"src/schema.rs":    schema,
		"src/schema.patch": patch,
	})
	for _, d := range diags {
		if d.Code == codeNotProven {
			t.Fatalf("the patch is not located: %s", d.Message)
		}
	}
	name := attrsOf(nodes, "column:src/schema.rs#users.name")
	if name["type"] != nil || name["nullable"] != nil || name["primary_key"] != false || claimVerification(name, "name") != models.VerificationMapped {
		t.Errorf("name %v", name)
	}
	kind := attrsOf(nodes, "column:src/schema.rs#users.kind")
	if kind["type"] != nil || kind["type_family"] != nil || kind["nullable"] != false || claimVerification(kind, "name") != models.VerificationOracle {
		t.Errorf("kind %v", kind)
	}
	if r := reasonText(kind); !strings.Contains(r, "the sql_types struct MyEnum is written by hand") {
		t.Errorf("kind reasons %q", r)
	}
	users := attrsOf(nodes, "table:src/schema.rs#users")
	if users["column_set"] != "complete" || users["verification"] != models.VerificationOracle {
		t.Errorf("users %v", users)
	}

	// A patch-added #[sql_name] above a key column: the key list no longer
	// names what print-schema wrote, so the primary key is unknown.
	keyed := "// @generated automatically by Diesel CLI.\n\ndiesel::table! {\n    things (code) {\n        #[sql_name = \"Code\"]\n        code -> Text,\n        n -> Int4,\n    }\n}\n"
	keyPatch := "--- a/src/schema.rs\n+++ b/src/schema.rs\n@@ -3,5 +3,6 @@\n diesel::table! {\n     things (code) {\n+        #[sql_name = \"Code\"]\n         code -> Text,\n         n -> Int4,\n     }\n"
	nodes, _, _ = linkPackage(t, "2.3.14", map[string]string{
		"diesel.toml":      "[print_schema]\nfile = \"src/schema.rs\"\npatch_file = \"src/schema.patch\"\n",
		"src/schema.rs":    keyed,
		"src/schema.patch": keyPatch,
	})
	things := attrsOf(nodes, "table:src/schema.rs#things")
	if things["primary_key"] != nil || !strings.Contains(reasonText(things), "adds an attribute line to the key column code") {
		t.Errorf("things %v", things)
	}
	if code := attrsOf(nodes, "column:src/schema.rs#things.code"); code["primary_key"] != nil || code["name"] != "Code" || claimVerification(code, "name") != models.VerificationMapped {
		t.Errorf("code %v", code)
	}
}

func reasonText(a map[string]any) string {
	list, _ := a["reasons"].([]models.Reason)
	var out []string
	for _, r := range list {
		out = append(out, r.Reason)
	}
	return strings.Join(out, "\n")
}

// TestDieselV24Output checks A4 and A2: diesel_cli 2.4's default output
// (an enum_type struct and the rust_types module) reads like 2.3's with
// the enum claimed as the plain type and no marker; an enum outside a
// rust_types module is still row D; timetz is its family; another custom
// type is its family with the generic modifiers unknown.
func TestDieselV24Output(t *testing.T) {
	schema := `// @generated automatically by Diesel CLI.

pub mod sql_types {
    #[derive(diesel::query_builder::QueryId, Clone, diesel::sql_types::SqlType)]
    #[diesel(postgres_type(name = "mood"))]
    #[diesel(enum_type)]
    pub struct Mood;

    #[derive(diesel::query_builder::QueryId, Clone, diesel::sql_types::SqlType)]
    #[diesel(postgres_type(name = "timetz", schema = "pg_catalog"))]
    pub struct Timetz;

    #[derive(diesel::query_builder::QueryId, Clone, diesel::sql_types::SqlType)]
    #[diesel(postgres_type(name = "vector"))]
    pub struct Vector;

    #[derive(diesel::query_builder::QueryId, Clone, diesel::sql_types::SqlType)]
    #[diesel(postgres_type(name = "point", schema = "pg_catalog"))]
    pub struct Point;
}

pub mod rust_types {
    #[derive(Debug, Clone, Copy, PartialEq, Eq, diesel::deserialize::FromSqlRow, diesel::expression::AsExpression)]
    #[diesel(sql_type = super::sql_types::Mood)]
    pub enum Mood {
        Sad,
        Ok,
    }
}

diesel::table! {
    use diesel::sql_types::*;
    use super::sql_types::{Mood, Timetz, Vector, Point};

    people (id) {
        id -> Int4,
        mood -> Mood,
        opens -> Timetz,
        embedding -> Vector,
        spot -> Point,
    }
}
`
	nodes, _, diags := linkPackage(t, "2.4.0", map[string]string{"src/schema.rs": schema})
	for _, d := range diags {
		t.Errorf("diagnostic %s %s", d.Code, d.Message)
	}
	col := func(name string) map[string]any { return attrsOf(nodes, "column:src/schema.rs#people."+name) }
	if a := col("mood"); a["type"] != "mood" {
		t.Errorf("mood %v", a)
	}
	if a := col("opens"); a["type"] != nil || !equalFamily(a["type_family"], models.TypeFamily("time with time zone", "precision")) {
		t.Errorf("opens %v", a)
	}
	if a := col("embedding"); a["type"] != nil || !equalFamily(a["type_family"], models.TypeFamily("vector", models.ModifiersUnknown)) {
		t.Errorf("embedding %v", a)
	}
	if _, has := col("embedding")[models.ModifiersUnknown]; has {
		t.Errorf("embedding has a %s attribute", models.ModifiersUnknown)
	}
	if a := col("spot"); a["type"] != "point" {
		t.Errorf("spot %v", a)
	}
	// A bare Timetz (no struct) is not print-schema output.
	nodes, _, _ = linkPackage(t, "2.4.0", map[string]string{"src/schema.rs": "// @generated automatically by Diesel CLI.\n\ndiesel::table! {\n    t (id) {\n        id -> Int4,\n        opens -> Timetz,\n    }\n}\n"})
	if a := attrsOf(nodes, "column:src/schema.rs#t.opens"); a["type"] != nil || a["type_family"] != nil {
		t.Errorf("bare Timetz %v", a)
	}
	// An enum outside a rust_types module, and a table! inside one, are
	// read as anywhere else.
	_, _, diags = linkPackage(t, "2.4.0", map[string]string{"src/schema.rs": "// @generated automatically by Diesel CLI.\n\npub enum Stray { A }\n\npub mod rust_types {\n    pub fn helper() {}\n}\n\ndiesel::table! {\n    t (id) {\n        id -> Int4,\n    }\n}\n"})
	var got []string
	for _, d := range diags {
		got = append(got, d.Message)
	}
	all := strings.Join(got, "\n")
	if !strings.Contains(all, "pub enum Stray outside a rust_types module (row D)") || !strings.Contains(all, "fn helper (row D)") {
		t.Errorf("diagnostics %s", all)
	}
}

func equalFamily(a, b any) bool {
	am, _ := a.(map[string]any)
	bm, _ := b.(map[string]any)
	if am == nil || bm == nil || am["name"] != bm["name"] {
		return false
	}
	return slices.Equal(stringList(am["unknown"]), stringList(bm["unknown"]))
}

// TestDieselVerificationLabels checks A6: on postgres, names on
// hand-written lines (a hand-written file, a patch-added line, an
// unconfigured schema.rs) are mapped; generated lines stay oracle.
func TestDieselVerificationLabels(t *testing.T) {
	nodes, _, _, _ := linkFixture(t)
	for id, want := range map[string]string{
		"column:pg/src/schema.rs#scalars.id":                   models.VerificationOracle,
		"column:pg/src/schema.rs#users.email":                  models.VerificationMapped,
		"column:pg/src/schema.rs#view_counts.n":                models.VerificationMapped,
		"column:pg/src/nohead.rs#handmade.note":                models.VerificationMapped,
		"column:pg/src/broken.rs#accounts.balance":             models.VerificationMapped,
		"column:worker/src/schema.rs#background_jobs.job_type": models.VerificationMapped,
		"column:pg/src/patched.rs#patched_users.name":          models.VerificationMapped,
	} {
		if got := claimVerification(attrsOf(nodes, id), "name"); got != want {
			t.Errorf("%s: name %s, want %s", id, got, want)
		}
	}
	for id, want := range map[string]string{
		"table:pg/src/schema.rs#scalars":             models.VerificationOracle,
		"table:pg/src/schema.rs#view_counts":         models.VerificationMapped,
		"table:pg/src/nohead.rs#handmade":            models.VerificationMapped,
		"table:worker/src/schema.rs#background_jobs": models.VerificationMapped,
	} {
		if got := attrsOf(nodes, id)["verification"]; got != want {
			t.Errorf("%s: verification %v, want %s", id, got, want)
		}
	}
}

// TestDieselLinkGuards checks the C guard: a failure in discovery or in
// the model kit's emit step becomes a diagnostic, never a failed run, and
// the other groups are still emitted.
func TestDieselLinkGuards(t *testing.T) {
	saved := faultHook
	t.Cleanup(func() { faultHook = saved })
	for _, step := range []string{"discovery", "emit"} {
		faultHook = func(s, subject string) {
			if s == step && (step == "discovery" || strings.Contains(subject, "pg/src/v24.rs")) {
				panic("injected")
			}
		}
		nodes, _, diags := Link(Input{Sources: readTree(t, fixtureDir)})
		internal := 0
		for _, d := range diags {
			if d.Code == "schema_model_internal_error" && strings.Contains(d.Message, "injected") {
				internal++
			}
		}
		if internal != 1 {
			t.Errorf("%s: %d internal-error diagnostics", step, internal)
		}
		switch step {
		case "discovery":
			if len(nodes) != 0 {
				t.Errorf("discovery failed but %d nodes were emitted", len(nodes))
			}
		case "emit":
			if attrsOf(nodes, "table:pg/src/v24.rs#people24") != nil || attrsOf(nodes, "table:pg/src/schema.rs#scalars") == nil {
				t.Errorf("emit: the failed group is emitted or another is not")
			}
		}
	}
}
