package schema

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strconv"
	"testing"
)

// amHandlers are the six core index access methods and the handler file
// that sets their IndexAmRoutine fields (REL_17_6).
var amHandlers = []struct{ name, file string }{
	{"btree", "src/backend/access/nbtree/nbtree.c"},
	{"hash", "src/backend/access/hash/hash.c"},
	{"gist", "src/backend/access/gist/gist.c"},
	{"gin", "src/backend/access/gin/ginutil.c"},
	{"spgist", "src/backend/access/spgist/spgutils.c"},
	{"brin", "src/backend/access/brin/brin.c"},
}

// TestGenerateAMCaps writes amcaps.go, the access-method capability table
// of T018a2 Revision 1.9 Y25, read from a PostgreSQL REL_17_6 source tree:
// amcanunique, amcanmulticol, amcanorder and amcaninclude of each core
// handler, whether it has amgettuple (EXCLUDE constraints need it), and
// INDEX_MAX_KEYS of pg_config_manual.h. It runs only when
// GRAPHVEIN_PG_SOURCE_DIR names the root of such a tree:
//
//	GRAPHVEIN_PG_SOURCE_DIR=<dir> go test ./internal/extract/schema -run TestGenerateAMCaps
func TestGenerateAMCaps(t *testing.T) {
	root := os.Getenv("GRAPHVEIN_PG_SOURCE_DIR")
	if root == "" {
		t.Skip("GRAPHVEIN_PG_SOURCE_DIR is not set; amcaps.go is generated on demand")
	}
	read := func(rel string) string {
		data, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			t.Fatal(err)
		}
		return string(data)
	}
	field := func(src, name string) bool {
		m := regexp.MustCompile(`amroutine->` + name + ` = ([A-Za-z_]+);`).FindStringSubmatch(src)
		if m == nil {
			t.Fatalf("no %s", name)
		}
		return m[1] != "false" && m[1] != "NULL"
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by TestGenerateAMCaps (amcaps_gen_test.go) from PostgreSQL\n")
	b.WriteString("// REL_17_6 index access method handlers and pg_config_manual.h; DO NOT EDIT.\n\npackage schema\n\n")
	b.WriteString("// amCaps are the IndexAmRoutine capabilities of the core access methods\n// (Y25): unique, multicol, order, include, gettuple.\nvar amCaps = map[string]amCapabilities{\n")
	for _, h := range amHandlers {
		src := read(h.file)
		fmt.Fprintf(&b, "\t%q: {unique: %v, multicol: %v, order: %v, include: %v, gettuple: %v},\n", h.name,
			field(src, "amcanunique"), field(src, "amcanmulticol"), field(src, "amcanorder"), field(src, "amcaninclude"), field(src, "amgettuple"))
	}
	b.WriteString("}\n\n")
	m := regexp.MustCompile(`#define INDEX_MAX_KEYS\s+(\d+)`).FindStringSubmatch(read("src/include/pg_config_manual.h"))
	if m == nil {
		t.Fatal("no INDEX_MAX_KEYS")
	}
	n, _ := strconv.Atoi(m[1])
	fmt.Fprintf(&b, "// indexMaxKeys is INDEX_MAX_KEYS.\nconst indexMaxKeys = %d\n", n)
	out, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("amcaps.go", out, 0o644); err != nil {
		t.Fatal(err)
	}
}
