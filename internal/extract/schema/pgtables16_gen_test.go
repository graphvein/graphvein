package schema

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"testing"
)

// TestGeneratePgTables16 writes pgtables16.go, the closed tables of T018a2
// Revision 1.6, read from a PostgreSQL REL_17_6 source tree:
//
//   - the pseudo-types of src/include/catalog/pg_type.dat (typtype p; V1,
//     V13);
//   - the encoding names of src/common/encnames.c pg_encname_tbl (V10);
//   - the PL/pgSQL condition names of src/backend/utils/errcodes.txt, as
//     generate-plerrcodes.pl selects them (V1);
//   - the PL/pgSQL keywords of src/pl/plpgsql/src/pl_reserved_kwlist.h and
//     pl_unreserved_kwlist.h (V1).
//
// The view options of reloptions.c (V12) and the operator classes'
// opcintype (V9) are already in pgtables.go (TestGeneratePgTables). It
// runs only when GRAPHVEIN_PG_SOURCE_DIR names the root of such a tree:
//
//	GRAPHVEIN_PG_SOURCE_DIR=<dir> go test ./internal/extract/schema -run TestGeneratePgTables16
func TestGeneratePgTables16(t *testing.T) {
	root := os.Getenv("GRAPHVEIN_PG_SOURCE_DIR")
	if root == "" {
		t.Skip("GRAPHVEIN_PG_SOURCE_DIR is not set; pgtables16.go is generated on demand")
	}
	read := func(rel string) string {
		data, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			t.Fatal(err)
		}
		return string(data)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by TestGeneratePgTables16 (pgtables16_gen_test.go) from PostgreSQL\n")
	b.WriteString("// REL_17_6 pg_type.dat, encnames.c, errcodes.txt and the PL/pgSQL keyword lists; DO NOT EDIT.\n\npackage schema\n\n")
	set := func(doc, name string, values []string) {
		fmt.Fprintf(&b, "%s\nvar %s = map[string]bool{\n", doc, name)
		for _, v := range sortedKeys(toSet(values)) {
			fmt.Fprintf(&b, "\t%q: true,\n", v)
		}
		b.WriteString("}\n\n")
	}

	// Pseudo-types: one pg_type.dat entry per brace block.
	var pseudo []string
	for _, entry := range regexp.MustCompile(`(?s)\{[^{}]*\}`).FindAllString(read("src/include/catalog/pg_type.dat"), -1) {
		if !strings.Contains(entry, "typtype => 'p'") {
			continue
		}
		if m := regexp.MustCompile(`typname => '([^']+)'`).FindStringSubmatch(entry); m != nil {
			pseudo = append(pseudo, m[1])
		}
	}
	set("// pgPseudoTypes are pg_type.dat's pseudo-types (typtype p; V1, V13).", "pgPseudoTypes", pseudo)

	// Encoding names (pg_encname_tbl), compared as pg_char_to_encoding
	// compares them (clean_encoding_name: alphanumerics, lower case).
	src := read("src/common/encnames.c")
	start := strings.Index(src, "pg_encname_tbl[] =")
	end := strings.Index(src[start:], "};")
	var names []string
	for _, m := range regexp.MustCompile(`"([a-z0-9_]+)", PG_(\w+)`).FindAllStringSubmatch(src[start:start+end], -1) {
		names = append(names, m[1]+"="+m[2])
	}
	b.WriteString("// pgEncodingNames are encnames.c's pg_encname_tbl names (cleaned as\n// clean_encoding_name cleans them) and their encodings (V10).\nvar pgEncodingNames = map[string]string{\n")
	for _, n := range sortedKeys(toSet(names)) {
		k, v, _ := strings.Cut(n, "=")
		fmt.Fprintf(&b, "\t%q: %q,\n", k, v)
	}
	b.WriteString("}\n\n")

	// PL/pgSQL condition names: error lines of errcodes.txt with a fourth
	// field (generate-plerrcodes.pl).
	var conds []string
	for _, line := range strings.Split(read("src/backend/utils/errcodes.txt"), "\n") {
		f := strings.Fields(line)
		if len(f) == 4 && f[1] == "E" && len(f[0]) == 5 {
			conds = append(conds, f[3])
		}
	}
	set("// plpgsqlConditions are the condition names of plerrcodes.h (V1).", "plpgsqlConditions", conds)

	// PL/pgSQL keywords.
	var plkw []string
	for _, f := range []string{"src/pl/plpgsql/src/pl_reserved_kwlist.h", "src/pl/plpgsql/src/pl_unreserved_kwlist.h"} {
		for _, m := range regexp.MustCompile(`PG_KEYWORD\("([a-z_]+)"`).FindAllStringSubmatch(read(f), -1) {
			plkw = append(plkw, m[1])
		}
	}
	set("// plpgsqlKeywords are the PL/pgSQL keywords of pl_reserved_kwlist.h and\n// pl_unreserved_kwlist.h (V1).", "plpgsqlKeywords", plkw)

	out, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("pgtables16.go", out, 0o644); err != nil {
		t.Fatal(err)
	}
}

func toSet(values []string) map[string]bool {
	m := map[string]bool{}
	for _, v := range values {
		m[v] = true
	}
	return m
}
