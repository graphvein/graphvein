// trigFunc writes a trigger function named f.
func trigFunc(f string) string {
	return fmt.Sprintf("CREATE FUNCTION %s() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$", f)
}

func genY01Identity(g *gen) (string, string, bool) {
	t := g.name("t")
	ident := pick(g, []string{"GENERATED ALWAYS AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY", "GENERATED BY DEFAULT AS IDENTITY (START WITH 5)"})
	sql := fmt.Sprintf("CREATE TABLE %s (a int %s, b int)", t, ident)
	col := "a"
	if g.chance(0.2) {
		sql += fmt.Sprintf(";\nALTER TABLE %s RENAME COLUMN a TO a2", t)
		col = "a2"
	}
	typ := pick(g, []string{"bigint", "int8", "smallint", "integer", "numeric", "text", "int4", "pg_catalog.int8", "real"})
	if g.chance(0.15) {
		d := g.name("d")
		sql += fmt.Sprintf(";\nCREATE DOMAIN %s AS bigint", d)
		typ = d
	}
	if g.chance(0.15) {
		sql += fmt.Sprintf(";\nALTER TABLE %s ALTER COLUMN %s DROP IDENTITY", t, col)
	}
	return sql + fmt.Sprintf(";\nALTER TABLE %s ALTER COLUMN %s TYPE %s", t, pick(g, []string{col, "b"}), typ), "M5c.identity_y01", true
}

func genY02RowType(g *gen) (string, string, bool) {
	t, u, ct := g.name("t"), g.name("u"), g.name("ct")
	sql := fmt.Sprintf("CREATE TABLE %s (a int, b varchar(5))", t)
	switch g.r.IntN(6) {
	case 0:
		sql += fmt.Sprintf(";\nCREATE TABLE %s (x %s)", u, t)
	case 1:
		sql += fmt.Sprintf(";\nCREATE TABLE %s (x %s[])", u, t)
	case 2:
		sql += fmt.Sprintf(";\nCREATE TYPE %s AS (x %s);\nCREATE TABLE %s (y %s)", ct, t, u, ct)
	case 3:
		sql += fmt.Sprintf(";\nCREATE TYPE %s AS (x %s)", ct, t)
	case 4:
		sql += fmt.Sprintf(";\nCREATE TABLE %s (x %s);\nDROP TABLE %s", u, t, u)
	default:
		sql += fmt.Sprintf(";\nCREATE TABLE %s (x int)", u)
	}
	name := t
	if g.chance(0.25) {
		name = g.name("t")
		sql += fmt.Sprintf(";\nALTER TABLE %s RENAME TO %s", t, name)
	}
	typ := pick(g, []string{"bigint", "varchar(9)", "text"})
	col := pick(g, []string{"a", "b"})
	if col == "b" && typ == "bigint" {
		typ = "varchar(20)"
	}
	return sql + fmt.Sprintf(";\nALTER TABLE %s ALTER COLUMN %s TYPE %s", name, col, typ), "M5c.rowtype_y02", true
}

// y19Relation creates a relation of a kind and returns its creating SQL
// and name.
func y19Relation(g *gen, kind string) (string, string) {
	n := g.name("r")
	switch kind {
	case "table":
		return fmt.Sprintf("CREATE TABLE %s (a int)", n), n
	case "partitioned table":
		return fmt.Sprintf("CREATE TABLE %s (a int) PARTITION BY RANGE (a)", n), n
	case "view":
		return fmt.Sprintf("CREATE VIEW %s AS SELECT 1 AS a", n), n
	case "materialized view":
		return fmt.Sprintf("CREATE MATERIALIZED VIEW %s AS SELECT 1 AS a", n), n
	case "sequence":
		return fmt.Sprintf("CREATE SEQUENCE %s", n), n
	case "composite type":
		return fmt.Sprintf("CREATE TYPE %s AS (a int)", n), n
	case "index":
		t := g.name("t")
		return fmt.Sprintf("CREATE TABLE %s (a int);\nCREATE INDEX %s ON %s (a)", t, n, t), n
	case "enum":
		return fmt.Sprintf("CREATE TYPE %s AS ENUM ('a')", n), n
	case "domain":
		return fmt.Sprintf("CREATE DOMAIN %s AS int", n), n
	}
	return "", n
}

var y19Kinds = []string{"table", "partitioned table", "view", "materialized view", "sequence", "composite type", "index"}

// y19Renamed renames a relation of a kind half of the time.
func y19Renamed(g *gen, kind, n string) (string, string) {
	if !g.chance(0.25) {
		return "", n
	}
	word := map[string]string{"table": "TABLE", "partitioned table": "TABLE", "view": "VIEW", "materialized view": "MATERIALIZED VIEW",
		"sequence": "SEQUENCE", "composite type": "TYPE", "index": "INDEX", "enum": "TYPE", "domain": "DOMAIN"}[kind]
	m := g.name("rn")
	return fmt.Sprintf(";\nALTER %s %s RENAME TO %s", word, n, m), m
}

func genY05Lock(g *gen) (string, string, bool) {
	kind := pick(g, y19Kinds)
	sql, n := y19Relation(g, kind)
	r, n := y19Renamed(g, kind, n)
	sql += r
	t := g.name("t")
	sql += fmt.Sprintf(";\nCREATE TABLE %s (a int)", t)
	target := pick(g, []string{n, n + ", " + t, t + ", " + n})
	mode := pick(g, []string{"", " IN SHARE MODE", " IN ACCESS EXCLUSIVE MODE", " IN ROW EXCLUSIVE MODE NOWAIT"})
	return sql + fmt.Sprintf(";\nLOCK %s%s%s", pick(g, []string{"", "TABLE ", "TABLE ONLY "}), target, mode), "T1.lockkind_y05", true
}

