func genY09TriggerFunctions(g *gen) (string, string, bool) {
	t, f, tr := g.name("t"), g.name("f"), g.name("tr")
	sql := fmt.Sprintf("CREATE TABLE %s (a int);\n", t)
	sql += pick(g, []string{
		trigFunc(f),
		fmt.Sprintf("CREATE FUNCTION %s() RETURNS void LANGUAGE plpgsql AS $$ BEGIN END $$", f),
		fmt.Sprintf("CREATE FUNCTION %s() RETURNS integer LANGUAGE plpgsql AS $$ BEGIN RETURN 1; END $$", f),
		fmt.Sprintf("CREATE FUNCTION %s() RETURNS event_trigger LANGUAGE plpgsql AS $$ BEGIN END $$", f),
		fmt.Sprintf("CREATE PROCEDURE %s() LANGUAGE plpgsql AS $$ BEGIN END $$", f),
		fmt.Sprintf("CREATE FUNCTION %s() RETURNS TRIGGER AS $f$ BEGIN RETURN NULL; END; $f$ LANGUAGE plpgsql", f),
	})
	if g.chance(0.2) {
		sql += fmt.Sprintf(";\nCREATE FUNCTION %s(x int) RETURNS int LANGUAGE plpgsql AS $$ BEGIN RETURN x; END $$", f)
	}
	return sql + fmt.Sprintf(";\nCREATE TRIGGER %s %s INSERT ON %s FOR EACH ROW EXECUTE %s %s()", tr, pick(g, []string{"BEFORE", "AFTER"}), t, pick(g, []string{"FUNCTION", "PROCEDURE"}), f), "N1.trigfunc_y09", true
}

func genY10TriggerKinds(g *gen) (string, string, bool) {
	kind := pick(g, append([]string{"table", "partitioned table", "view", "view"}, y19Kinds...))
	sql, n := y19Relation(g, kind)
	r, n := y19Renamed(g, kind, n)
	f, tr := g.name("f"), g.name("tr")
	sql += r + ";\n" + trigFunc(f)
	timing := pick(g, []string{"BEFORE", "AFTER", "INSTEAD OF"})
	event := pick(g, []string{"INSERT", "UPDATE", "DELETE", "TRUNCATE", "INSERT OR UPDATE"})
	level := pick(g, []string{"FOR EACH ROW", "FOR EACH STATEMENT", ""})
	if event == "TRUNCATE" && level == "FOR EACH ROW" {
		level = ""
	}
	if g.chance(0.15) {
		// O1t: the axum installer.
		h := g.name("h")
		sql += fmt.Sprintf(";\nCREATE FUNCTION %s(tablename regclass) RETURNS void AS $$ BEGIN EXECUTE format('CREATE TRIGGER %s BEFORE UPDATE ON %%s FOR EACH ROW WHEN (OLD IS DISTINCT FROM NEW) EXECUTE FUNCTION %s();', tablename); END; $$ LANGUAGE plpgsql;\nSELECT %s('%s')", h, tr, f, h, n)
		return sql, "N1.trigkind_y10", true
	}
	return sql + fmt.Sprintf(";\nCREATE TRIGGER %s %s %s ON %s %s EXECUTE FUNCTION %s()", tr, timing, event, n, level, f), "N1.trigkind_y10", true
}

