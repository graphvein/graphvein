func genY16AlterFunction(g *gen) (string, string, bool) {
	f, f2 := g.name("f"), g.name("f")
	kind := pick(g, []string{"function", "setof", "procedure"})
	var sql string
	switch kind {
	case "function":
		sql = fmt.Sprintf("CREATE FUNCTION %s() RETURNS int LANGUAGE plpgsql AS $$ BEGIN RETURN 1; END $$", f)
	case "setof":
		sql = fmt.Sprintf("CREATE FUNCTION %s() RETURNS SETOF int LANGUAGE plpgsql AS $$ BEGIN RETURN; END $$", f)
	default:
		sql = fmt.Sprintf("CREATE PROCEDURE %s() LANGUAGE plpgsql AS $$ BEGIN END $$", f)
	}
	word := map[string]string{"function": "FUNCTION", "setof": "FUNCTION", "procedure": "PROCEDURE"}[kind]
	if g.chance(0.2) {
		word = "ROUTINE"
	}
	if g.chance(0.3) {
		sql += fmt.Sprintf(";\nCREATE FUNCTION %s() RETURNS int LANGUAGE plpgsql AS $$ BEGIN RETURN 2; END $$", f2)
		return sql + fmt.Sprintf(";\nALTER %s %s%s RENAME TO %s", word, f, pick(g, []string{"()", ""}), pick(g, []string{f2, g.name("f")})), "R6.alterfunc_y16", true
	}
	action := pick(g, []string{"COST -1", "COST 10", "COST 0", "ROWS 10", "IMMUTABLE VOLATILE", "STABLE", "STRICT", "CALLED ON NULL INPUT",
		"PARALLEL SAFE", "PARALLEL bogus", "LEAKPROOF", "SECURITY DEFINER", "STABLE STRICT RESTRICT", "STRICT STRICT"})
	return sql + fmt.Sprintf(";\nALTER %s %s() %s", word, f, action), "R6.alterfunc_y16", true
}

