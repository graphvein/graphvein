package schema

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
	"testing"
)

// TestGeneratePgTables writes pgtables.go, the closed tables of T018a2
// Revision 1.5 (U7, U8, U9 and the E1 amendment), read from a PostgreSQL
// REL_17_6 source tree:
//
//   - keyword categories (src/include/parser/kwlist.h, U8);
//   - operator classes with their defaults (src/include/catalog/
//     pg_opclass.dat, U7) and the collations of pg_collation.dat;
//   - run-time parameters (src/backend/utils/misc/guc_tables.c, with the
//     enum value lists wherever they are defined, and the prefixes a module
//     reserves with MarkGUCPrefixReserved, U7);
//   - storage parameters (src/backend/access/common/reloptions.c, U9);
//   - the E1 types and operator classes of contrib/*/*--*.sql.
//
// It runs only when GRAPHVEIN_PG_SOURCE_DIR names the root of such a tree
// (cloned into scratch, never committed):
//
//	GRAPHVEIN_PG_SOURCE_DIR=<dir> go test ./internal/extract/schema -run TestGeneratePgTables
func TestGeneratePgTables(t *testing.T) {
	root := os.Getenv("GRAPHVEIN_PG_SOURCE_DIR")
	if root == "" {
		t.Skip("GRAPHVEIN_PG_SOURCE_DIR is not set; pgtables.go is generated on demand")
	}
	read := func(rel string) string {
		data, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			t.Fatal(err)
		}
		return string(data)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by TestGeneratePgTables (pgtables_gen_test.go) from PostgreSQL REL_17_6\n")
	b.WriteString("// kwlist.h, pg_opclass.dat, pg_collation.dat, guc_tables.c, reloptions.c and contrib; DO NOT EDIT.\n\npackage schema\n\n")

	// Keywords (U8).
	kw := map[string]string{}
	for _, m := range regexp.MustCompile(`PG_KEYWORD\("([a-z_]+)", \w+, (\w+)_KEYWORD`).FindAllStringSubmatch(read("src/include/parser/kwlist.h"), -1) {
		kw[m[1]] = map[string]string{"UNRESERVED": "U", "COL_NAME": "C", "TYPE_FUNC_NAME": "T", "RESERVED": "R"}[m[2]]
	}
	b.WriteString("// pgKeywordCategories are the keyword categories of kwlist.h: U unreserved,\n// C col_name, T type_func_name, R reserved (U8).\nvar pgKeywordCategories = map[string]byte{\n")
	for _, k := range sortedKeys(kw) {
		fmt.Fprintf(&b, "\t%q: '%s',\n", k, kw[k])
	}
	b.WriteString("}\n\n")

	// Operator classes and collations (U7).
	b.WriteString("// pgOpclasses are pg_opclass.dat's operator classes (U7).\nvar pgOpclasses = []pgOpclass{\n")
	for _, r := range datRecords(read("src/include/catalog/pg_opclass.dat")) {
		fmt.Fprintf(&b, "\t{%q, %q, %q, %v},\n", r["opcmethod"], r["opcname"], r["opcintype"], r["opcdefault"] != "f")
	}
	b.WriteString("}\n\n// pgCollationNames are pg_collation.dat's collations, which exist under\n// every provider (U7).\nvar pgCollationNames = map[string]bool{\n")
	for _, r := range datRecords(read("src/include/catalog/pg_collation.dat")) {
		fmt.Fprintf(&b, "\t%q: true,\n", r["collname"])
	}
	b.WriteString("}\n\n")

	// Constants for bounds: numeric #defines of src/include and the
	// limits gram.y and guc_tables.c use.
	defines := map[string]string{"INT_MAX": "2147483647", "INT_MIN": "-2147483648", "DBL_MAX": "1.7976931348623157e+308", "MAX_KILOBYTES": "2147483647", "PG_INT32_MAX": "2147483647"}
	defineRe := regexp.MustCompile(`(?m)^#define\s+([A-Z_][A-Z0-9_]*)\s+(-?[0-9]+(?:\.[0-9]+)?)\s*(?:/\*.*)?$`)
	filepath.WalkDir(filepath.Join(root, "src/include"), func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".h") {
			return nil
		}
		data, _ := os.ReadFile(p)
		for _, m := range defineRe.FindAllStringSubmatch(string(data), -1) {
			if _, ok := defines[m[1]]; !ok {
				defines[m[1]] = m[2]
			}
		}
		return nil
	})
	bound := func(s string) string {
		s = strings.TrimSpace(s)
		if v, ok := defines[s]; ok {
			return v
		}
		if _, err := strconv.ParseFloat(s, 64); err == nil {
			return s
		}
		return "" // unknown: any value may fail
	}

	// Enum value lists of run-time parameters, wherever they are defined.
	enumLists := map[string][]string{}
	enumDecl := regexp.MustCompile(`config_enum_entry\s+(\w+)\[\]\s*=\s*\{`)
	filepath.WalkDir(filepath.Join(root, "src"), func(p string, d os.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".c") {
			return nil
		}
		data, _ := os.ReadFile(p)
		text := cStrip(string(data))
		for _, loc := range enumDecl.FindAllStringSubmatchIndex(text, -1) {
			name := text[loc[2]:loc[3]]
			body := braceBody(text, loc[1]-1)
			for _, e := range braceEntries(body) {
				parts := splitTop(e)
				if len(parts) > 0 && strings.HasPrefix(parts[0], `"`) {
					enumLists[name] = append(enumLists[name], strings.ToLower(strings.Trim(parts[0], `"`)))
				}
			}
		}
		return nil
	})

	// Run-time parameters (U7, N2.P1/P4/P5).
	guc := cStripKeepIf(read("src/backend/utils/misc/guc_tables.c"))
	type gucRow struct{ name, line string }
	var gucs []gucRow
	for _, arr := range []struct{ name, typ string }{{"ConfigureNamesBool", "b"}, {"ConfigureNamesInt", "i"}, {"ConfigureNamesReal", "r"}, {"ConfigureNamesString", "s"}, {"ConfigureNamesEnum", "e"}} {
		at := strings.Index(guc, arr.name+"[] =")
		if at < 0 {
			t.Fatalf("guc_tables.c: %s not found", arr.name)
		}
		body := braceBody(guc, strings.Index(guc[at:], "{")+at)
		for _, e := range braceEntriesIf(body) {
			parts := splitTop(e.text)
			if len(parts) < 2 || !strings.HasPrefix(parts[0], "{") {
				continue
			}
			gen := splitTop(strings.TrimSuffix(strings.TrimPrefix(parts[0], "{"), "}"))
			if len(gen) < 2 || !strings.HasPrefix(gen[0], `"`) {
				continue
			}
			name := strings.ToLower(strings.Trim(gen[0], `"`))
			flags := ""
			if len(gen) >= 6 {
				flags = gen[5]
			}
			rest := parts[1:]
			g := pgGUC{context: strings.ToLower(strings.TrimPrefix(gen[1], "PGC_")), typ: arr.typ[0], conditional: e.conditional, unit: strings.Contains(flags, "GUC_UNIT"), noReset: strings.Contains(flags, "GUC_NO_RESET")}
			hooks := rest[len(rest)-3:]
			g.check = strings.TrimSpace(hooks[0]) != "NULL"
			switch arr.typ {
			case "i", "r":
				g.min, g.max = bound(rest[2]), bound(rest[3])
			case "e":
				// "list + n" skips the list's first n entries.
				list, skip, _ := strings.Cut(strings.TrimSpace(rest[2]), "+")
				g.enum = enumLists[strings.TrimSpace(list)]
				if n, err := strconv.Atoi(strings.TrimSpace(skip)); err == nil && n <= len(g.enum) {
					g.enum = g.enum[n:]
				}
				if g.enum == nil {
					t.Fatalf("guc_tables.c: enum list %s of %s not found", rest[2], name)
				}
			}
			gucs = append(gucs, gucRow{name, fmt.Sprintf("{%q, '%c', %q, %q, %v, %#v, %v, %v, %v}", g.context, g.typ, g.min, g.max, g.unit, g.enum, g.check, g.conditional, g.noReset)})
		}
	}
	sort.Slice(gucs, func(i, j int) bool { return gucs[i].name < gucs[j].name })
	b.WriteString("// pgGUCs are guc_tables.c's run-time parameters by lower-case name (U7).\nvar pgGUCs = map[string]pgGUC{\n")
	for _, g := range gucs {
		fmt.Fprintf(&b, "\t%q: %s,\n", g.name, strings.ReplaceAll(g.line, "[]string(nil)", "nil"))
	}
	b.WriteString("}\n\n")
	reserved := map[string]bool{}
	for _, dir := range []string{"src", "contrib"} {
		filepath.WalkDir(filepath.Join(root, dir), func(p string, d os.DirEntry, err error) error {
			if err != nil || d.IsDir() || !strings.HasSuffix(p, ".c") {
				return nil
			}
			data, _ := os.ReadFile(p)
			for _, m := range regexp.MustCompile(`MarkGUCPrefixReserved\("([^"]+)"\)`).FindAllStringSubmatch(string(data), -1) {
				reserved[strings.ToLower(m[1])] = true
			}
			return nil
		})
	}
	b.WriteString("// pgReservedGUCPrefixes are the placeholder prefixes a REL_17_6 module\n// reserves with MarkGUCPrefixReserved once it is loaded (U7).\nvar pgReservedGUCPrefixes = map[string]bool{\n")
	for _, k := range sortedKeys(reserved) {
		fmt.Fprintf(&b, "\t%q: true,\n", k)
	}
	b.WriteString("}\n\n")

	// Storage parameters (U9).
	rel := cStrip(read("src/backend/access/common/reloptions.c"))
	kindRe := regexp.MustCompile(`RELOPT_KIND_([A-Z]+)`)
	type reloptRow struct{ name, line string }
	var relopts []reloptRow
	for _, arr := range []struct{ name, typ string }{{"boolRelOpts", "b"}, {"intRelOpts", "i"}, {"realRelOpts", "r"}, {"enumRelOpts", "e"}, {"stringRelOpts", "s"}} {
		at := strings.Index(rel, arr.name+"[] =")
		if at < 0 {
			t.Fatalf("reloptions.c: %s not found", arr.name)
		}
		body := braceBody(rel, strings.Index(rel[at:], "{")+at)
		for _, e := range braceEntries(body) {
			parts := splitTop(e)
			if len(parts) < 2 {
				continue
			}
			gen := splitTop(strings.TrimSuffix(strings.TrimPrefix(parts[0], "{"), "}"))
			if len(gen) < 3 || !strings.HasPrefix(gen[0], `"`) {
				continue
			}
			var kinds []string
			for _, k := range kindRe.FindAllStringSubmatch(gen[2], -1) {
				kinds = append(kinds, strings.ToLower(k[1]))
			}
			o := pgRelopt{kinds: kinds, typ: arr.typ[0]}
			switch arr.typ {
			case "i", "r":
				o.min, o.max = bound(parts[2]), bound(parts[3])
			case "e":
				list := strings.TrimSpace(parts[1])
				vals := regexp.MustCompile(`\{\s*"([^"]+)"`).FindAllStringSubmatch(braceBody(rel, strings.Index(rel, list+"[] =")+len(list)+5), -1)
				for _, v := range vals {
					o.enum = append(o.enum, strings.ToLower(v[1]))
				}
				if o.enum == nil {
					t.Fatalf("reloptions.c: enum list %s not found", list)
				}
			}
			relopts = append(relopts, reloptRow{strings.Trim(gen[0], `"`), fmt.Sprintf("{%#v, '%c', %q, %q, %#v}", o.kinds, o.typ, o.min, o.max, o.enum)})
		}
	}
	sort.SliceStable(relopts, func(i, j int) bool { return relopts[i].name < relopts[j].name })
	b.WriteString("// pgRelopts are reloptions.c's storage parameters by name, one entry\n// per definition (U9).\nvar pgRelopts = map[string][]pgRelopt{\n")
	for i := 0; i < len(relopts); {
		j := i
		var lines []string
		for ; j < len(relopts) && relopts[j].name == relopts[i].name; j++ {
			lines = append(lines, strings.ReplaceAll(relopts[j].line, "[]string(nil)", "nil"))
		}
		fmt.Fprintf(&b, "\t%q: {%s},\n", relopts[i].name, strings.Join(lines, ", "))
		i = j
	}
	b.WriteString("}\n\n")

	// E1 types and operator classes of contrib (E1 amendment).
	types := map[string]bool{}
	var opclasses []string
	typeRe := regexp.MustCompile(`(?is)\bCREATE\s+TYPE\s+(?:[a-z_]+\.)?([a-z_0-9]+)`)
	opcRe := regexp.MustCompile(`(?is)\bCREATE\s+OPERATOR\s+CLASS\s+(?:[a-z_]+\.)?([a-z_0-9]+)\s+(DEFAULT\s+)?FOR\s+TYPE\s+(?:[a-z_]+\.)?([a-z_0-9]+(?:\[\])?)\s+USING\s+([a-z_0-9]+)`)
	scripts, _ := filepath.Glob(filepath.Join(root, "contrib", "*", "*--*.sql"))
	sort.Strings(scripts)
	seen := map[string]bool{}
	for _, p := range scripts {
		data, _ := os.ReadFile(p)
		text := stripComments(string(data))
		for _, m := range typeRe.FindAllStringSubmatch(text, -1) {
			types[strings.ToLower(m[1])] = true
		}
		for _, m := range opcRe.FindAllStringSubmatch(text, -1) {
			line := fmt.Sprintf("{%q, %q, %q, %v}", strings.ToLower(m[4]), strings.ToLower(m[1]), strings.ToLower(m[3]), m[2] != "")
			if !seen[line] {
				seen[line] = true
				opclasses = append(opclasses, line)
			}
		}
	}
	sort.Strings(opclasses)
	b.WriteString("// e1Types are the types contrib's extension scripts create (E1).\nvar e1Types = map[string]bool{\n")
	for _, k := range sortedKeys(types) {
		fmt.Fprintf(&b, "\t%q: true,\n", k)
	}
	b.WriteString("}\n\n// e1Opclasses are the operator classes contrib's extension scripts\n// create, with the defaults they declare (E1).\nvar e1Opclasses = []pgOpclass{\n")
	for _, l := range opclasses {
		fmt.Fprintf(&b, "\t%s,\n", l)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatalf("formatting pgtables.go: %v", err)
	}
	if err := os.WriteFile("pgtables.go", src, 0o644); err != nil {
		t.Fatal(err)
	}
}

// cStrip removes C comments and preprocessor lines.
func cStrip(s string) string {
	s = regexp.MustCompile(`(?s)/\*.*?\*/`).ReplaceAllString(s, " ")
	return regexp.MustCompile(`(?m)^\s*#.*$`).ReplaceAllString(s, "")
}

// cStripKeepIf removes C comments and keeps #if/#ifdef/#endif lines (as
// "@if"/"@endif" markers) so that braceEntriesIf can mark conditional
// entries.
func cStripKeepIf(s string) string {
	s = regexp.MustCompile(`(?s)/\*.*?\*/`).ReplaceAllString(s, " ")
	s = regexp.MustCompile(`(?m)^\s*#\s*if.*$`).ReplaceAllString(s, " @if ")
	s = regexp.MustCompile(`(?m)^\s*#\s*endif.*$`).ReplaceAllString(s, " @endif ")
	return regexp.MustCompile(`(?m)^\s*#.*$`).ReplaceAllString(s, "")
}

// braceBody returns the text inside the braces that open at s[open].
func braceBody(s string, open int) string {
	depth := 0
	inStr := false
	for i := open; i < len(s); i++ {
		switch c := s[i]; {
		case inStr && c == '\\':
			i++
		case c == '"':
			inStr = !inStr
		case inStr:
		case c == '{':
			depth++
		case c == '}':
			depth--
			if depth == 0 {
				return s[open+1 : i]
			}
		}
	}
	return ""
}

// braceEntries returns the top-level {...} groups of an array body.
func braceEntries(body string) []string {
	var out []string
	for _, e := range braceEntriesIf(body) {
		out = append(out, e.text)
	}
	return out
}

type cEntry struct {
	text        string
	conditional bool
}

// braceEntriesIf is braceEntries that also reports whether an entry sits
// inside an @if ... @endif block (cStripKeepIf).
func braceEntriesIf(body string) []cEntry {
	var out []cEntry
	ifDepth := 0
	for i := 0; i < len(body); i++ {
		switch {
		case strings.HasPrefix(body[i:], "@if"):
			ifDepth++
		case strings.HasPrefix(body[i:], "@endif"):
			ifDepth--
		case body[i] == '{':
			inner := braceBody(body, i)
			out = append(out, cEntry{strings.TrimSpace(inner), ifDepth > 0})
			i += len(inner) + 1
		}
	}
	return out
}

// splitTop splits a C initializer list at its top-level commas.
func splitTop(s string) []string {
	var out []string
	depth, start := 0, 0
	inStr := false
	for i := 0; i < len(s); i++ {
		switch c := s[i]; {
		case inStr && c == '\\':
			i++
		case c == '"':
			inStr = !inStr
		case inStr:
		case c == '{' || c == '(':
			depth++
		case c == '}' || c == ')':
			depth--
		case c == ',' && depth == 0:
			out = append(out, strings.TrimSpace(s[start:i]))
			start = i + 1
		}
	}
	if last := strings.TrimSpace(s[start:]); last != "" {
		out = append(out, last)
	}
	return out
}
