// TestGenerateSuperuserForms writes superuser.go, the table of Y51's
// superuser-only checks (superuserForms), from a PostgreSQL REL_17_6
// source tree. It runs only when GRAPHVEIN_PG_SOURCE_DIR names the root of
// such a tree:
//
//	GRAPHVEIN_PG_SOURCE_DIR=<dir> go test ./internal/extract/schema -run TestGenerateSuperuserForms
func TestGenerateSuperuserForms(t *testing.T) {
	root := os.Getenv("GRAPHVEIN_PG_SOURCE_DIR")
	if root == "" {
		t.Skip("GRAPHVEIN_PG_SOURCE_DIR is not set; superuser.go is generated on demand")
	}
	msg := regexp.MustCompile(`(?:errmsg|gettext_noop)\("((?:[^"\\]|\\.)*)"`)
	detail := regexp.MustCompile(`errdetail\("((?:[^"\\]|\\.)*)"`)
	var b bytes.Buffer
	b.WriteString("// Code generated by TestGenerateSuperuserForms (superuser_gen_test.go) from PostgreSQL REL_17_6; DO NOT EDIT.\n\npackage schema\n\n")
	b.WriteString("// superuserForms are the checks of REL_17_6 that only a superuser passes\n// (T018a2 Revision 1.9 Y51, D-superuser): the statement form, the source\n// line and the message (and detail) Postgres raises.\nvar superuserForms = []superuserForm{\n")
	for _, s := range superuserSources {
		file, lineText, _ := strings.Cut(s.file, ":")
		var line int
		fmt.Sscan(lineText, &line)
		data, err := os.ReadFile(filepath.Join(root, file))
		if err != nil {
			t.Fatal(err)
		}
		lines := strings.Split(string(data), "\n")
		if line < 1 || line > len(lines) {
			t.Fatalf("%s: no line %d", file, line)
		}
		// The message of the check: the first errmsg (or gettext_noop) at
		// or after a few lines before the cited one, and its detail.
		from := max(line-4, 0)
		window := strings.Join(lines[from:min(line+8, len(lines))], "\n")
		m := msg.FindStringSubmatch(lines[line-1])
		if m == nil {
			m = msg.FindStringSubmatch(window)
		}
		if m == nil {
			t.Fatalf("%s: no message near line %d", file, line)
		}
		d := ""
		if dm := detail.FindStringSubmatchIndex(window); dm != nil && dm[0] > strings.Index(window, m[0]) {
			// The detail of the same ereport: before the next errmsg.
			if next := msg.FindStringIndex(window[strings.Index(window, m[0])+len(m[0]):]); next == nil || dm[0] < strings.Index(window, m[0])+len(m[0])+next[0] {
				d = window[dm[2]:dm[3]]
			}
		}
		fmt.Fprintf(&b, "\t{form: %q, source: %q, message: %q, detail: %q},\n", s.form, strings.TrimPrefix(s.file, "src/backend/"), unescapeC(m[1]), unescapeC(d))
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("superuser.go", out, 0o644); err != nil {
		t.Fatal(err)
	}
}

// unescapeC undoes the C string escapes a message uses (\" and \\).
func unescapeC(s string) string {
	return strings.NewReplacer(`\"`, `"`, `\\`, `\`).Replace(s)
}
