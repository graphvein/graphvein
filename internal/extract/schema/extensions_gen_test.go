package schema

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"testing"
)

// TestGenerateExtensions writes extensions.go, the contrib extension tables
// of T018a2 Revision 1.9 Y33 and Y34, read from a PostgreSQL REL_17_6
// source tree: for every contrib/*/*.control, the default version, the
// required extensions, the versions that have an install script
// (name--v.sql) and the update scripts (name--a--b.sql), and the names
// its scripts create (functions, procedures, aggregates, types, domains,
// operator classes and families, lower-cased, without a schema) and
// whether they create operators. It runs only when
// GRAPHVEIN_PG_SOURCE_DIR names the root of such a tree:
//
//	GRAPHVEIN_PG_SOURCE_DIR=<dir> go test ./internal/extract/schema -run TestGenerateExtensions
func TestGenerateExtensions(t *testing.T) {
	root := os.Getenv("GRAPHVEIN_PG_SOURCE_DIR")
	if root == "" {
		t.Skip("GRAPHVEIN_PG_SOURCE_DIR is not set; extensions.go is generated on demand")
	}
	controls, err := filepath.Glob(filepath.Join(root, "contrib", "*", "*.control"))
	if err != nil || len(controls) == 0 {
		t.Fatalf("no contrib control files under %s: %v", root, err)
	}
	keyValue := regexp.MustCompile(`(?m)^\s*(\w+)\s*=\s*'([^']*)'`)
	member := regexp.MustCompile(`(?i)\bCREATE\s+(?:OR\s+REPLACE\s+)?(?:FUNCTION|PROCEDURE|AGGREGATE|TYPE|DOMAIN|OPERATOR\s+CLASS|OPERATOR\s+FAMILY)\s+((?:@extschema@\.|"?\w+"?\.)?"?[\w]+"?)`)
	operator := regexp.MustCompile(`(?i)\bCREATE\s+OPERATOR\s+[^CF\s]`)
	type ext struct {
		def      string
		requires []string
		installs []string
		updates  [][2]string
		members  map[string]bool
		ops      bool
		trusted  bool
	}
	exts := map[string]*ext{}
	for _, ctl := range controls {
		name := strings.TrimSuffix(filepath.Base(ctl), ".control")
		data, err := os.ReadFile(ctl)
		if err != nil {
			t.Fatal(err)
		}
		e := &ext{members: map[string]bool{}}
		// Y51 (Revision 1.9): a control file with trusted = true may be
		// installed by a role that is not a superuser.
		e.trusted = regexp.MustCompile(`(?m)^\s*trusted\s*=\s*true\b`).Match(data)
		for _, m := range keyValue.FindAllStringSubmatch(string(data), -1) {
			switch m[1] {
			case "default_version":
				e.def = m[2]
			case "requires":
				for _, r := range strings.Split(m[2], ",") {
					if r = strings.TrimSpace(r); r != "" {
						e.requires = append(e.requires, r)
					}
				}
			}
		}
		scripts, _ := filepath.Glob(filepath.Join(filepath.Dir(ctl), name+"--*.sql"))
		for _, sc := range scripts {
			parts := strings.Split(strings.TrimSuffix(strings.TrimPrefix(filepath.Base(sc), name+"--"), ".sql"), "--")
			switch len(parts) {
			case 1:
				e.installs = append(e.installs, parts[0])
			case 2:
				e.updates = append(e.updates, [2]string{parts[0], parts[1]})
			default:
				continue
			}
			body, err := os.ReadFile(sc)
			if err != nil {
				t.Fatal(err)
			}
			for _, m := range member.FindAllStringSubmatch(string(body), -1) {
				n := strings.ToLower(strings.ReplaceAll(m[1], `"`, ""))
				if i := strings.LastIndexByte(n, '.'); i >= 0 {
					n = n[i+1:]
				}
				e.members[n] = true
			}
			if operator.Match(body) {
				e.ops = true
			}
		}
		sort.Strings(e.installs)
		sort.Slice(e.updates, func(i, j int) bool {
			return e.updates[i][0] < e.updates[j][0] || e.updates[i][0] == e.updates[j][0] && e.updates[i][1] < e.updates[j][1]
		})
		exts[name] = e
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by TestGenerateExtensions (extensions_gen_test.go) from PostgreSQL REL_17_6\n")
	b.WriteString("// contrib/*/*.control and the extension scripts; DO NOT EDIT.\n\npackage schema\n\n")
	b.WriteString("// e1ExtensionVersions are the contrib extensions of REL_17_6 (Y33): the\n// default version, the required extensions, the versions with an install\n// script and the update scripts (from, to).\nvar e1ExtensionVersions = map[string]extVersions{\n")
	for _, n := range sortedKeys(exts) {
		e := exts[n]
		fmt.Fprintf(&b, "\t%q: {def: %q, requires: %#v, installs: %#v, updates: %#v, operators: %v, trusted: %v},\n", n, e.def, e.requires, e.installs, e.updates, e.ops, e.trusted)
	}
	b.WriteString("}\n\n// e1ExtensionMembers are the names the scripts of each contrib extension\n// create (Y34): functions, procedures, aggregates, types, domains,\n// operator classes and operator families.\nvar e1ExtensionMembers = map[string][]string{\n")
	for _, n := range sortedKeys(exts) {
		fmt.Fprintf(&b, "\t%q: %#v,\n", n, sortedKeys(exts[n].members))
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatalf("formatting: %v\n%s", err, b.String())
	}
	if err := os.WriteFile("extensions.go", out, 0o644); err != nil {
		t.Fatal(err)
	}
}
