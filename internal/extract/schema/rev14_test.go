func TestRev14Cases(t *testing.T) {
	for _, tc := range rev14Cases {
		t.Run(tc.name, func(t *testing.T) {
			applied, diagnostics := linkSQL(t, tc.sql)
			if applied["1_m.sql"] != tc.want {
				t.Fatalf("applied %v, want %s; %v", applied, tc.want, diagnostics)
			}
			if tc.cite != "" && !cites(diagnostics, tc.cite) {
				t.Fatalf("no diagnostic cites %s: %v", tc.cite, diagnostics)
			}
			if tc.want == "true" && tc.pg != "ok" {
				t.Fatalf("the case claims applied, but Postgres refuses it (%s)", tc.pg)
			}
		})
	}
}

func TestRev14CasesPostgres(t *testing.T) {
	db, err := egress.OpenPostgres(oracleURL(t), nil)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	ctx := context.Background()
	for _, tc := range rev14Cases {
		t.Run(tc.name, func(t *testing.T) {
			if got := runRolledBack(ctx, t, db, tc.sql); got != tc.pg {
				t.Fatalf("Postgres: %s, the case says %s", got, tc.pg)
			}
		})
	}
}

// TestRev14Typmods pins typmodCheck (R4) for the stored type of a time
// precision above 6.
func TestRev14Typmods(t *testing.T) {
	for _, tc := range []struct {
		typ, stored string
		v           typmodVerdict
	}{
		{"timestamp(7)", "timestamp(6)", typmodOK},
		{"TIMESTAMP (9) WITH TIME ZONE", "TIMESTAMP (6) WITH TIME ZONE", typmodOK},
		{"time(3)", "time(3)", typmodOK},
		{"varchar(10485760)", "varchar(10485760)", typmodOK},
		{"varchar(10485761)", "varchar(10485761)", typmodRefused},
		{"bit varying(83886080)", "bit varying(83886080)", typmodOK},
		{"numeric(5,-1001)", "numeric(5,-1001)", typmodRefused},
		{"float(54)", "float(54)", typmodRefused},
		{"interval(7)", "interval(7)", typmodUnknown},
		{"geometry(Point, 4326)", "geometry(Point, 4326)", typmodUnknown},
	} {
		stored, v, _ := typmodCheck(tc.typ)
		if stored != tc.stored || v != tc.v {
			t.Errorf("%s: %q %v, want %q %v", tc.typ, stored, v, tc.stored, tc.v)
		}
	}
}

// TestRev14ObjectNames pins makeObjectName (R2) against Postgres's
// truncation: the longer part is cut first.
func TestRev14ObjectNames(t *testing.T) {
	long := "abcdefghijklmnopqrstuvwxyzabcdefghijklmnopqrstuvwxyzabcdefghij"
	cols := "c1"
	got, _ := makeObjectName(long, &cols, "fkey")
	if len(got) != maxIdentifier || got != long[:55]+"_c1_fkey" {
		t.Errorf("makeObjectName: %q (%d)", got, len(got))
	}
	if !mayBeChosen("t_a_check1", "t", strPtr("a"), "check") || mayBeChosen("t_b_check", "t", strPtr("a"), "check") {
		t.Errorf("mayBeChosen: wrong candidates")
	}
}

