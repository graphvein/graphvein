// TestGeneratePgCatalog writes pgcatalog.go, the closed pg_catalog tables
// of class P5 (T018a2 Revision 1 and 1.1): functions, casts, operators and
// type I/O volatility, read from PostgreSQL REL_17_6
// src/include/catalog/{pg_proc,pg_type,pg_cast,pg_operator}.dat. It runs
// only when GRAPHVEIN_PG_CATALOG_DIR names a directory holding those four
// files (fetched into scratch, never committed):
//
//	GRAPHVEIN_PG_CATALOG_DIR=<dir> go test ./internal/extract/schema -run TestGeneratePgCatalog
//
// TestPgCatalogServer checks the generated tables against a live server.
func TestGeneratePgCatalog(t *testing.T) {
	dir := os.Getenv("GRAPHVEIN_PG_CATALOG_DIR")
	if dir == "" {
		t.Skip("GRAPHVEIN_PG_CATALOG_DIR is not set; pgcatalog.go is generated on demand")
	}
	read := func(name string) []map[string]string {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		return datRecords(string(data))
	}
	types := read("pg_type.dat")
	procs := read("pg_proc.dat")
	casts := read("pg_cast.dat")
	operators := read("pg_operator.dat")

	// Array types are written <element>[] in canonicalType's form.
	arrayOf := map[string]string{}
	for _, ty := range types {
		if ty["array_type_oid"] != "" {
			arrayOf["_"+ty["typname"]] = ty["typname"] + "[]"
		}
	}
	typeName := func(n string) string {
		if a, ok := arrayOf[n]; ok {
			return a
		}
		return n
	}
	// Volatility by function name and by name(args), defaults per pg_proc.h.
	volByName := map[string]string{}
	volBySig := map[string]string{}
	for _, p := range procs {
		v := p["provolatile"]
		if v == "" {
			v = "i"
		}
		name := p["proname"]
		if old, ok := volByName[name]; ok && old != v {
			volByName[name] = "?"
		} else if !ok {
			volByName[name] = v
		}
		if src := p["prosrc"]; src != "" && src != name {
			// oprcode and typinput name the C symbol through prosrc when
			// proname differs (rare); record both.
			if _, ok := volByName[src]; !ok {
				volByName[src] = v
			}
		}
		volBySig[name+"("+strings.ReplaceAll(p["proargtypes"], " ", ",")+")"] = v
	}

	var b bytes.Buffer
	b.WriteString("// Code generated by TestGeneratePgCatalog (pgcatalog_gen_test.go) from PostgreSQL REL_17_6\n")
	b.WriteString("// src/include/catalog/{pg_proc,pg_type,pg_cast,pg_operator}.dat; DO NOT EDIT.\n\n")
	b.WriteString("package schema\n\n")

	// Functions.
	byName := map[string][]string{}
	for _, p := range procs {
		vol := p["provolatile"]
		if vol == "" {
			vol = "i"
		}
		kind := p["prokind"]
		if kind == "" {
			kind = "f"
		}
		var args []string
		for _, a := range strings.Fields(p["proargtypes"]) {
			args = append(args, typeName(a))
		}
		variadic := p["provariadic"] != "" && p["provariadic"] != "0" || strings.Contains(p["proargmodes"], "v")
		entry := fmt.Sprintf("{%q, %q, '%s', '%s', %t, %t}", strings.Join(args, " "), typeName(p["prorettype"]), vol, kind, p["proretset"] == "t", variadic)
		byName[p["proname"]] = append(byName[p["proname"]], entry)
	}
	b.WriteString("// pgProcs are pg_catalog's functions by name, one entry per overload.\nvar pgProcs = map[string][]pgProc{\n")
	for _, name := range sortedKeys(byName) {
		fmt.Fprintf(&b, "%q: {%s},\n", name, strings.Join(byName[name], ", "))
	}
	b.WriteString("}\n\n")

	// Types: category and the volatility of their I/O functions.
	b.WriteString("// pgTypes are pg_catalog's base types: category and the volatility of\n// their input and output functions (a CoerceViaIO cast uses both).\nvar pgTypes = map[string]pgType{\n")
	typeLines := map[string]string{}
	for _, ty := range types {
		in, out := volByName[ty["typinput"]], volByName[ty["typoutput"]]
		typeLines[ty["typname"]] = fmt.Sprintf("{'%s', '%s', '%s'}", ty["typcategory"], in, out)
	}
	for _, n := range sortedKeys(typeLines) {
		fmt.Fprintf(&b, "%q: %s,\n", n, typeLines[n])
	}
	b.WriteString("}\n\n")

	// Casts.
	b.WriteString("// pgCasts are pg_cast's entries: context (e, a, i), method (f, i, b)\n// and the volatility of the cast function ('i' for binary casts; for I/O\n// casts the types' I/O functions decide, see castVolatility).\nvar pgCasts = map[[2]string]pgCast{\n")
	var castLines []string
	for _, c := range casts {
		vol := "i"
		if c["castmethod"] == "f" {
			fn := c["castfunc"]
			if v, ok := volBySig[fn]; ok {
				vol = v
			} else if v, ok := volByName[strings.SplitN(fn, "(", 2)[0]]; ok {
				vol = v
			} else {
				t.Fatalf("cast function %s not found", fn)
			}
		}
		castLines = append(castLines, fmt.Sprintf("{%q, %q}: {'%s', '%s', '%s'},", typeName(c["castsource"]), typeName(c["casttarget"]), c["castcontext"], c["castmethod"], vol))
	}
	sort.Strings(castLines)
	b.WriteString(strings.Join(castLines, "\n"))
	b.WriteString("\n}\n\n")

	// Operators.
	ops := map[string][]string{}
	for _, o := range operators {
		vol, ok := volByName[o["oprcode"]]
		if !ok {
			vol, ok = volBySig[o["oprcode"]]
		}
		if !ok {
			t.Fatalf("operator function %s not found", o["oprcode"])
		}
		left := o["oprleft"]
		if left == "0" {
			left = ""
		}
		ops[o["oprname"]] = append(ops[o["oprname"]], fmt.Sprintf("{%q, %q, %q, '%s'}", typeName(left), typeName(o["oprright"]), typeName(o["oprresult"]), vol))
	}
	b.WriteString("// pgOperators are pg_operator's entries by name: left and right operand\n// types (left empty for a prefix operator), result type and the\n// volatility of the operator's function.\nvar pgOperators = map[string][]pgOperator{\n")
	for _, name := range sortedKeys(ops) {
		fmt.Fprintf(&b, "%q: {%s},\n", name, strings.Join(ops[name], ", "))
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile("pgcatalog.go", src, 0o644); err != nil {
		t.Fatal(err)
	}
}

// datRecords reads the records of a catalog .dat file: each { ... } holds
// key => 'value' pairs (values with \' escapes).
func datRecords(data string) []map[string]string {
	var out []map[string]string
	pair := regexp.MustCompile(`(\w+) => '((?:[^'\\]|\\.)*)'`)
	var lines []string
	for _, l := range strings.Split(data, "\n") {
		if strings.HasPrefix(strings.TrimSpace(l), "#") {
			continue
		}
		lines = append(lines, l)
	}
	text := strings.Join(lines, "\n")
	depth, start := 0, 0
	inQuote := false
	for i := 0; i < len(text); i++ {
		switch ch := text[i]; {
		case ch == '\\' && inQuote:
			i++
		case ch == '\'':
			inQuote = !inQuote
		case ch == '{' && !inQuote:
			if depth == 0 {
				start = i
			}
			depth++
		case ch == '}' && !inQuote:
			depth--
			if depth == 0 {
				rec := map[string]string{}
				for _, m := range pair.FindAllStringSubmatch(text[start:i], -1) {
					rec[m[1]] = strings.ReplaceAll(m[2], `\'`, `'`)
				}
				out = append(out, rec)
			}
		}
	}
	return out
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// TestPgCatalogServer confirms the generated tables against a live
// Postgres 17 server (the oracle, P5: "each pair confirmed by the
// oracle"): every pg_catalog function overload with its result type,
// volatility, kind and set-returning flag, every cast with its context and
// method, and every operator with its result type and the volatility of
// its function. Minor releases do not change these catalogs.
func TestPgCatalogServer(t *testing.T) {
	o := sharedOracle(t)
	ctx := context.Background()
	// Array types are _<element>; int2vector and oidvector keep their names.
	typ := `CASE WHEN t.typname LIKE '\_%' AND t.typelem <> 0 AND e.typname IS NOT NULL THEN e.typname || '[]' ELSE t.typname END`
	join := func(col, alias string) string {
		return fmt.Sprintf("JOIN pg_type %[2]s_t ON %[2]s_t.oid = %[1]s LEFT JOIN pg_type %[2]s_e ON %[2]s_e.oid = %[2]s_t.typelem", col, alias)
	}
	name := func(alias string) string {
		return strings.ReplaceAll(strings.ReplaceAll(typ, "t.", alias+"_t."), "e.", alias+"_e.")
	}
	query := func(q string, row func(*sql.Rows) (string, error)) map[string]bool {
		rows, err := o.db.QueryContext(ctx, q)
		if err != nil {
			t.Fatal(err)
		}
		defer rows.Close()
		out := map[string]bool{}
		for rows.Next() {
			k, err := row(rows)
			if err != nil {
				t.Fatal(err)
			}
			out[k] = true
		}
		return out
	}
	// Functions: compared by name, result, volatility, kind and set (the
	// argument lists of oidvector columns are compared by count).
	live := query(`SELECT p.proname, `+name("r")+`, p.provolatile, p.prokind, p.proretset, p.pronargs FROM pg_proc p `+join("p.prorettype", "r")+` WHERE p.pronamespace = 'pg_catalog'::regnamespace AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.classid = 'pg_proc'::regclass AND d.objid = p.oid AND d.deptype = 'e')`, func(r *sql.Rows) (string, error) {
		var n, ret, vol, kind string
		var set bool
		var nargs int
		err := r.Scan(&n, &ret, &vol, &kind, &set, &nargs)
		return fmt.Sprintf("%s|%s|%s|%s|%t|%d", n, ret, vol, kind, set, nargs), err
	})
	var serverVersion int
	if err := o.db.QueryRowContext(ctx, `SELECT current_setting('server_version_num')::int`).Scan(&serverVersion); err != nil {
		t.Fatal(err)
	}
	for k := range live {
		fn := strings.SplitN(k, "|", 2)[0]
		if catalogOutsideDat[fn] {
			delete(live, k)
			continue
		}
		if added, ok := catalogAddedAfterREL17_6[fn]; ok && pgProcs[fn] == nil && serverVersion >= added {
			t.Logf("function %s: added in %d after REL_17_6, not in the generated catalog (tolerated)", k, added)
			delete(live, k)
		}
	}
	gen := map[string]bool{}
	for n, procs := range pgProcs {
		for _, p := range procs {
			gen[fmt.Sprintf("%s|%s|%c|%c|%t|%d", n, p.ret, p.vol, p.kind, p.set, len(strings.Fields(p.args)))] = true
		}
	}
	compareSets(t, "functions", gen, live)
	liveCasts := query(`SELECT `+name("s")+`, `+name("d")+`, c.castcontext, c.castmethod FROM pg_cast c `+join("c.castsource", "s")+` `+join("c.casttarget", "d"), func(r *sql.Rows) (string, error) {
		var s, d, ctxt, method string
		err := r.Scan(&s, &d, &ctxt, &method)
		return s + "|" + d + "|" + ctxt + "|" + method, err
	})
	genCasts := map[string]bool{}
	for k, c := range pgCasts {
		genCasts[fmt.Sprintf("%s|%s|%c|%c", k[0], k[1], c.context, c.method)] = true
	}
	compareSets(t, "casts", genCasts, liveCasts)
	liveOps := query(`SELECT o.oprname, coalesce(`+name("l")+`, ''), `+name("rr")+`, `+name("res")+`, p.provolatile FROM pg_operator o JOIN pg_proc p ON p.oid = o.oprcode LEFT JOIN pg_type l_t ON l_t.oid = o.oprleft LEFT JOIN pg_type l_e ON l_e.oid = l_t.typelem `+join("o.oprright", "rr")+` `+join("o.oprresult", "res"), func(r *sql.Rows) (string, error) {
		var n, l, rt, res, vol string
		err := r.Scan(&n, &l, &rt, &res, &vol)
		return strings.Join([]string{n, l, rt, res, vol}, "|"), err
	})
	genOps := map[string]bool{}
	for n, ops := range pgOperators {
		for _, op := range ops {
			genOps[fmt.Sprintf("%s|%s|%s|%s|%c", n, op.left, op.right, op.result, op.vol)] = true
		}
	}
	compareSets(t, "operators", genOps, liveOps)
}

// catalogAddedAfterREL17_6 are the pg_catalog functions that PostgreSQL 17
// minor releases after REL_17_6 added, by the server_version_num of the
// release that added them. The generated catalog stays REL_17_6's (the
// extractor's catalog is a fixed, documented release); CI's postgres:17
// image follows the newest minor release, so TestPgCatalogServer tolerates
// exactly these names on a server at least that new, and only while the
// generated catalog lacks them. Any other difference still fails.
//
// 17.12 (CVE-2026-6460, row-layout versioning of composite datums) added
// binary_upgrade_set_next_attribute_versions(pg_lsn[]) for pg_upgrade.
// Casts and operators did not change. The extractor does not know these
// names, so calls to them are never proven (TestCatalogAddedAfterDatUnproven).
var catalogAddedAfterREL17_6 = map[string]int{
	"binary_upgrade_set_next_attribute_versions": 170012,
}

// TestCatalogAddedAfterDatUnproven checks that the extractor claims nothing
// for a migration that calls a function of catalogAddedAfterREL17_6: on a
// REL_17_6 server the function does not exist, on a newer one it is a
// pg_catalog function (never E1) that refuses outside binary upgrade mode,
// so the migration's applied state must stay unknown, never true or false.
func TestCatalogAddedAfterDatUnproven(t *testing.T) {
	for fn := range catalogAddedAfterREL17_6 {
		for i, sql := range []string{
			"SELECT " + fn + "(ARRAY[]::pg_lsn[]);",
			"CREATE TABLE t (a pg_lsn[]);\nCREATE INDEX t_i ON t ((" + fn + "(a)));",
			"CREATE TABLE t (a text DEFAULT " + fn + "(ARRAY[]::pg_lsn[])::text);",
		} {
			h := &oracleHistory{ID: fmt.Sprintf("after-dat-%d", i), Files: []oracleFile{{Name: "0001_a.sql", SQL: sql}}}
			x, err := extract(h, t.TempDir())
			if err != nil {
				t.Fatal(err)
			}
			for name, m := range x.migrations {
				if m.applied != nil {
					t.Errorf("%s case %d: migration %s claims applied=%t; want unknown", fn, i, name, *m.applied)
				}
			}
		}
	}
}

func compareSets(t *testing.T, what string, gen, live map[string]bool) {
	t.Helper()
	var missing, extra []string
	for k := range gen {
		if !live[k] {
			missing = append(missing, k)
		}
	}
	for k := range live {
		if !gen[k] {
			extra = append(extra, k)
		}
	}
	sort.Strings(missing)
	sort.Strings(extra)
	if len(missing)+len(extra) > 0 {
		t.Errorf("%s: %d generated entries not on the server (%v), %d server entries not generated (%v)", what, len(missing), missing[:min(5, len(missing))], len(extra), extra[:min(5, len(extra))])
	}
}
