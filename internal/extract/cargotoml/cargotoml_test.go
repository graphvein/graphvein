func TestParse(t *testing.T) {
	root, err := Parse("\ufeff# c\n[package]\nname = \"a\" # trailing\n'quoted key' = 'lit'\n" +
		"[dependencies]\nx = { version = \"1\", features = [\n  \"f\",\n] }\n" +
		"[[bin]]\nname = \"one\"\n[[bin]]\nname = \"two\"\n[bin.extra]\nk = true\n" +
		"[a.b]\nc.d = 1\nml = \"\"\"\nline\\n\"\"\"\n")
	if err != nil {
		t.Fatal(err)
	}
	pkg := root["package"].(Table)
	if pkg["name"] != "a" || pkg["quoted key"] != "lit" {
		t.Errorf("package %v", pkg)
	}
	bins := root["bin"].([]any)
	if len(bins) != 2 || bins[1].(Table)["name"] != "two" || bins[1].(Table)["extra"].(Table)["k"] != Scalar("true") {
		t.Errorf("bins %v", bins)
	}
	if root["a"].(Table)["b"].(Table)["c"].(Table)["d"] != Scalar("1") || root["a"].(Table)["b"].(Table)["ml"] != "line\n" {
		t.Errorf("a.b %v", root["a"])
	}
	_, err = Parse("[package]\nname = \"a\"\nname = \"b\"\n")
	var pe *ParseError
	if !errors.As(err, &pe) || pe.Line != 3 || err.Error() != "line 3: key name defined twice" {
		t.Errorf("duplicate key: %v", err)
	}
}

func TestDependencyTablesAndFeatures(t *testing.T) {
	root, err := Parse("[dependencies]\na = \"1\"\n[dev-dependencies]\nb = { version = \"1\", features = [\"x\", \"y\"] }\n" +
		"[target.'cfg(unix)'.dependencies]\nc = \"1\"\n[target.wasm.dev-dependencies]\nd = { features = 3 }\n")
	if err != nil {
		t.Fatal(err)
	}
	tables := DependencyTables(root)
	if len(tables) != 4 || tables[2]["c"] != "1" || tables[3]["d"] == nil {
		t.Fatalf("tables %v", tables)
	}
	if f, ok := Features(tables[1]["b"]); !ok || !reflect.DeepEqual(f, []string{"x", "y"}) {
		t.Errorf("features %v %v", f, ok)
	}
	if f, ok := Features(tables[0]["a"]); !ok || f != nil {
		t.Errorf("string entry %v %v", f, ok)
	}
	if _, ok := Features(tables[3]["d"]); ok {
		t.Errorf("features = 3 must not be readable")
	}
	// AllDependencyTables adds build-dependencies, at the top level and
	// under a target.
	root, err = Parse("[dependencies]\na = \"1\"\n[build-dependencies]\nb = \"1\"\n[target.wasm.build-dependencies]\nc = \"1\"\n")
	if err != nil {
		t.Fatal(err)
	}
	if n := len(DependencyTables(root)); n != 1 {
		t.Errorf("DependencyTables: %d tables, want 1", n)
	}
	all := AllDependencyTables(root)
	if len(all) != 3 || all[1]["b"] != "1" || all[2]["c"] != "1" {
		t.Errorf("AllDependencyTables %v", all)
	}
}

func TestReadLock(t *testing.T) {
	lock := `# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "diesel"
version = "2.3.14"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abc"
dependencies = [
 "diesel_derives",
 "pq-sys",
]

[[package]]
name = "app"
version = "0.1.0"
dependencies = [
 "diesel 2.3.14",
 "diesel 1.4.8 (registry+https://github.com/rust-lang/crates.io-index)",
]

[[package]]
name = "diesel"
version = "1.4.8"
source = "registry+https://github.com/rust-lang/crates.io-index"

[metadata]
"checksum diesel 1.4.8 (registry+https://github.com/rust-lang/crates.io-index)" = "x"
`
	pkgs, err := ReadLock(lock)
	if err != nil {
		t.Fatal(err)
	}
	if len(pkgs) != 3 || !reflect.DeepEqual(pkgs[1], LockedPackage{Name: "app", Version: "0.1.0", Dependencies: []string{"diesel", "diesel"},
		DependencyEntries: []string{"diesel 2.3.14", "diesel 1.4.8 (registry+https://github.com/rust-lang/crates.io-index)"}}) ||
		!reflect.DeepEqual(pkgs[0].Dependencies, []string{"diesel_derives", "pq-sys"}) {
		t.Errorf("packages %+v", pkgs)
	}
	if v := LockedVersions(append(pkgs, pkgs[0]), "diesel"); !reflect.DeepEqual(v, []string{"1.4.8", "2.3.14"}) {
		t.Errorf("versions %v", v)
	}
	if pkgs, err := ReadLock("version = 4\n"); err != nil || pkgs != nil {
		t.Errorf("empty lock %v %v", pkgs, err)
	}
	for _, bad := range []string{"[[package]]\nname = \"x\"\n", "package = 1\n", "[[package\n",
		"[[package]]\nname = \"x\"\nversion = \"1\"\ndependencies = \"y\"\n", "[[package]]\nname = \"x\"\nversion = \"1\"\ndependencies = [\" \"]\n"} {
		if _, err := ReadLock(bad); err == nil {
			t.Errorf("ReadLock(%q): want an error", bad)
		}
	}
}
