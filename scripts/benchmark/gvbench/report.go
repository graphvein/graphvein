package main

import (
	"fmt"
	"sort"
	"strings"
)

// writeReport renders summary.md from the rows: one table per agent and
// mode with correctness and the median (min-max) of every metric, then the
// per-question correctness k/n. Runs that never started are listed apart and
// are not counted as failures.
func writeReport(rows []Row) string {
	type group struct {
		key  string
		rows []Row
	}
	groups := map[string]*group{}
	var order []string
	for _, r := range rows {
		k := r.Agent + "\x00" + r.Harness + " " + r.HarnessVersion + "\x00" + r.Model + "\x00" + r.Mode
		if groups[k] == nil {
			groups[k] = &group{key: k}
			order = append(order, k)
		}
		groups[k].rows = append(groups[k].rows, r)
	}
	sort.Strings(order)
	var b strings.Builder
	b.WriteString("# Benchmark summary\n\n")
	b.WriteString("Generated by `gvbench report` from runs.jsonl. Metrics are median (min-max) over runs that started; ")
	b.WriteString("\"not run\" rows never started (total cap or rate limit) and are not failures.\n\n")
	b.WriteString("| Agent | Harness | Model | Mode | Started | Correct | Not run | Timeout / error / invalid / cost cap | Input | Cache read | Output | Cost USD (kind) | Tool calls | MCP calls | Wall s |\n")
	b.WriteString("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
	for _, k := range order {
		g := groups[k]
		parts := strings.Split(k, "\x00")
		var started []Row
		notRun, timeouts, errs, invalid, capped, correct := 0, 0, 0, 0, 0, 0
		kinds := map[string]bool{}
		for _, r := range g.rows {
			switch r.Outcome {
			case outcomeNotRunCap, outcomeNotRunRate, outcomeNotRunPreflight:
				notRun++
				continue
			case outcomeTimeout:
				timeouts++
			case outcomeAgentError, outcomeTurnLimit:
				errs++
			case outcomeInvalid:
				invalid++
			case outcomeCostCap:
				capped++
			}
			if r.Correct {
				correct++
			}
			kinds[r.CostKind] = true
			started = append(started, r)
		}
		pick := func(f func(Row) float64) string {
			var xs []float64
			for _, r := range started {
				xs = append(xs, f(r))
			}
			return medianRange(xs)
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %d | %d/%d | %d | %d / %d / %d / %d | %s | %s | %s | %s (%s) | %s | %s | %s |\n",
			parts[0], parts[1], parts[2], parts[3], len(started), correct, len(started), notRun,
			timeouts, errs, invalid, capped,
			pick(func(r Row) float64 { return float64(r.InputTokens) }),
			pick(func(r Row) float64 { return float64(r.CacheReadTokens) }),
			pick(func(r Row) float64 { return float64(r.OutputTokens) }),
			pick(func(r Row) float64 { return r.CostUSD }), strings.Join(sortedKeys(kinds), ","),
			pick(func(r Row) float64 { return float64(r.ToolCalls) }),
			pick(func(r Row) float64 { return float64(r.MCPToolCalls) }),
			pick(func(r Row) float64 { return float64(r.WallMS) / 1000 }),
		)
	}

	b.WriteString("\n## Correct runs per question\n\n")
	cols := order
	b.WriteString("| Question |")
	for _, k := range cols {
		p := strings.Split(k, "\x00")
		fmt.Fprintf(&b, " %s %s |", p[0], p[3])
	}
	b.WriteString("\n|---|")
	for range cols {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	qset := map[string]bool{}
	for _, r := range rows {
		qset[r.Question] = true
	}
	qs := sortedKeys(qset)
	sort.SliceStable(qs, func(i, j int) bool { return questionNumber(qs[i]) < questionNumber(qs[j]) })
	for _, q := range qs {
		fmt.Fprintf(&b, "| %s |", q)
		for _, k := range cols {
			ok, n, nr := 0, 0, 0
			for _, r := range groups[k].rows {
				if r.Question != q {
					continue
				}
				if strings.HasPrefix(r.Outcome, "not_run") {
					nr++
					continue
				}
				n++
				if r.Correct {
					ok++
				}
			}
			cell := fmt.Sprintf("%d/%d", ok, n)
			if nr > 0 {
				cell += fmt.Sprintf(" (+%d not run)", nr)
			}
			fmt.Fprintf(&b, " %s |", cell)
		}
		b.WriteString("\n")
	}

	writeSpend(&b, rows)
	writeRegradeSection(&b, rows)

	var flagged []string
	for _, r := range rows {
		if r.Serving != nil && r.Serving.Elsewhere {
			flagged = append(flagged, fmt.Sprintf("- %s: served by %s (%s), evidence %s", r.RunID, r.Serving.Provider, r.Serving.Endpoint, r.Serving.Evidence))
		}
	}
	if len(flagged) > 0 {
		b.WriteString("\n## Runs served outside the preferred endpoints\n\n")
		b.WriteString(strings.Join(flagged, "\n") + "\n")
	}
	return b.String()
}

// writeSpend lists, per agent and billing, how many runs were billed and
// what they cost in total. The rows are the last row of each run; superseded
// invalid attempts are in runs.jsonl and in the cap's ledger.
func writeSpend(b *strings.Builder, rows []Row) {
	type spend struct {
		runs  int
		usd   float64
		kinds map[string]bool
	}
	by := map[string]*spend{}
	var keys []string
	for _, r := range rows {
		billing := r.Billing
		switch {
		case r.Agent == "opencode":
			billing = "OpenRouter"
		case billing == "":
			continue
		}
		if strings.HasPrefix(r.Outcome, "not_run") || billing == "subscription" {
			continue
		}
		k := r.Agent + "\x00" + billing
		if by[k] == nil {
			by[k] = &spend{kinds: map[string]bool{}}
			keys = append(keys, k)
		}
		by[k].runs++
		by[k].usd += r.CostUSD
		by[k].kinds[r.CostKind] = true
	}
	if len(keys) == 0 {
		return
	}
	sort.Strings(keys)
	b.WriteString("\n## Spend\n\n")
	b.WriteString("Real spend only (subscription runs are not billed per run). `api_billed` is Claude Code's own reported cost; ")
	b.WriteString("`api_billed_worst_case` and `worst_case_unsettled` are worst-case bookings of runs whose cost was not reported.\n\n")
	b.WriteString("| Agent | Billing | Runs | Cost USD | Cost kinds |\n|---|---|---|---|---|\n")
	for _, k := range keys {
		p := strings.Split(k, "\x00")
		sp := by[k]
		fmt.Fprintf(b, "| %s | %s | %d | %.4f | %s |\n", p[0], p[1], sp.runs, sp.usd, strings.Join(sortedKeys(sp.kinds), ","))
	}
}

func questionNumber(id string) int {
	n := 0
	fmt.Sscanf(strings.TrimPrefix(id, "BQ-"), "%d", &n)
	return n
}

func medianRange(xs []float64) string {
	if len(xs) == 0 {
		return "-"
	}
	sort.Float64s(xs)
	var med float64
	if len(xs)%2 == 1 {
		med = xs[len(xs)/2]
	} else {
		med = (xs[len(xs)/2-1] + xs[len(xs)/2]) / 2
	}
	return fmt.Sprintf("%s (%s-%s)", short(med), short(xs[0]), short(xs[len(xs)-1]))
}

func short(x float64) string {
	switch {
	case x == float64(int64(x)):
		return fmt.Sprintf("%d", int64(x))
	case x < 1:
		return fmt.Sprintf("%.4f", x)
	default:
		return fmt.Sprintf("%.1f", x)
	}
}
