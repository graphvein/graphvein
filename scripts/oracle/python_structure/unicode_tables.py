"""Unicode-version differences for the Python structural claim contract
(docs/lang/python-structure.md, row PS-F2 form `unicode_version`, ADR 0069).

The extractor normalises identifiers with golang.org/x/text's NFKC tables,
confirms `\\N{...}` names with its rune-name tables and sorts constant names
with Go's `unicode` categories. Under the Go toolchain in go.mod these tables
are a newer Unicode version than the reference CPython's `unicodedata`.
This script lists every code point whose identifier-relevant properties
differ between the two versions, so the extractor refuses a file using one
instead of claiming what the reference Python would not.

Modes (run each `dump` with the interpreter whose Unicode data it reads;
`-I` keeps the working directory out of `sys.path`):

    python3.14 -I unicode_tables.py dump > ref.tsv     # reference, Unicode 16
    python3.15 -I unicode_tables.py dump > new.tsv     # Unicode of the tables
    python3 -I unicode_tables.py go ref.tsv new.tsv > internal/lang/python/unicodeversion.go

`dump` prints one header line (`#` + unicodedata.unidata_version + the
interpreter version) and one line per code point 0..0x10FFFF: the code point
(hex), whether it can start an identifier (`c.isidentifier()`), whether it
can continue one (`("a" + c).isidentifier()`), its general category, its
canonical combining class, its NFKC form (hex code points) and its name
(`unicodedata.name`, empty when it has none).

`go` compares two dumps and writes two Go lists of code points, as sorted
ranges: `identifierChanged`, where the start or continue property, the
category class Go's `unicode.IsLetter`/`IsUpper`/`IsDigit` read, the
combining class or the NFKC form differ; and `nameChanged`, where the name
differs. A code point new in the later version that can be part of an
identifier differs at least in its continue property, so every new
identifier character is in the first list. Normalisation of a whole identifier is the composition of the
per-character data compared here (decompositions, combining classes and the
composition pairs of characters on both sides): Unicode's stability policy
adds composition pairs only with new characters, which the list holds.
"""

import sys
import unicodedata

MAX = 0x10FFFF


def dump():
    out = sys.stdout
    out.write("#%s %s\n" % (unicodedata.unidata_version, sys.version.split()[0]))
    for cp in range(MAX + 1):
        c = chr(cp)
        start = "1" if c.isidentifier() else "0"
        cont = "1" if ("a" + c).isidentifier() else "0"
        nfkc = " ".join("%X" % ord(x) for x in unicodedata.normalize("NFKC", c))
        out.write(
            "%X\t%s\t%s\t%s\t%d\t%s\t%s\n"
            % (cp, start, cont, unicodedata.category(c), unicodedata.combining(c), nfkc, unicodedata.name(c, ""))
        )


def read(path):
    with open(path, encoding="utf-8") as f:
        header = f.readline().rstrip("\n")
        if not header.startswith("#"):
            raise SystemExit("%s: no header line" % path)
        version, python = header[1:].split()
        rows = [line.rstrip("\n").split("\t", 1)[1] for line in f]
    if len(rows) != MAX + 1:
        raise SystemExit("%s: %d code points, want %d" % (path, len(rows), MAX + 1))
    return version, python, rows


def identifier_fields(row):
    """The fields an identifier depends on: start, continue, the category
    class Go's unicode.IsUpper/IsLetter/IsDigit read (Lu, other letters, Nd,
    other), the combining class and the NFKC form."""
    start, cont, cat, ccc, nfkc, _name = row.split("\t")
    if cat == "Lu" or cat == "Nd":
        cls = cat
    elif cat.startswith("L"):
        cls = "L"
    else:
        cls = "-"
    return (start, cont, cls, ccc, nfkc)


def name_field(row):
    return row.split("\t")[5]


def ranges_of(ref, new, field):
    ranges = []
    count = 0
    for cp in range(MAX + 1):
        if field(ref[cp]) == field(new[cp]):
            continue
        count += 1
        if ranges and ranges[-1][1] == cp - 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ranges, count


def go(ref_path, new_path):
    ref_version, ref_python, ref = read(ref_path)
    new_version, new_python, new = read(new_path)
    ident, ident_count = ranges_of(ref, new, identifier_fields)
    names, names_count = ranges_of(ref, new, name_field)
    w = sys.stdout.write
    w("package python\n\n")
    w("// Code generated by scripts/oracle/python_structure/unicode_tables.py go\n")
    w("// from the unicodedata of CPython %s (Unicode %s) and CPython %s\n" % (ref_python, ref_version, new_python))
    w("// (Unicode %s); DO NOT EDIT by hand.\n" % new_version)
    w("//\n")
    w("// Row PS-F2, forms unicode_version and string_literal, of\n")
    w("// docs/lang/python-structure.md. TestPythonUnicodeVersion checks the\n")
    w("// versions against the tables in use and, with an interpreter of either\n")
    w("// version, every code point against Go's tables.\n\n")
    w("// unicodeReference is the Unicode version of the reference Python's\n")
    w("// unicodedata, which decides identifiers and their normalisation.\n")
    w('const unicodeReference = "%s"\n\n' % ref_version)
    w("// unicodeTables is the Unicode version the lists were generated for: the\n")
    w("// version of golang.org/x/text's tables and Go's unicode package under\n")
    w("// the toolchain in go.mod.\n")
    w('const unicodeTables = "%s"\n\n' % new_version)
    w("// identifierChangedCount and nameChangedCount are the numbers of code\n")
    w("// points in identifierChanged and nameChanged.\n")
    w("const (\n\tidentifierChangedCount = %d\n\tnameChangedCount       = %d\n)\n\n" % (ident_count, names_count))
    w("// identifierChanged lists, as sorted inclusive ranges, the code points\n")
    w("// whose identifier start or continue property, letter, upper-case letter\n")
    w("// or decimal digit class, combining class or NFKC form differ between\n")
    w("// unicodeReference and unicodeTables.\n")
    w("var identifierChanged = [][2]rune{\n")
    for lo, hi in ident:
        w("\t{0x%04X, 0x%04X},\n" % (lo, hi))
    w("}\n\n")
    w("// nameChanged lists, as sorted inclusive ranges, the code points whose\n")
    w("// character name differs between unicodeReference and unicodeTables.\n")
    w("var nameChanged = [][2]rune{\n")
    for lo, hi in names:
        w("\t{0x%04X, 0x%04X},\n" % (lo, hi))
    w("}\n")


def main():
    if len(sys.argv) == 2 and sys.argv[1] == "dump":
        dump()
    elif len(sys.argv) == 4 and sys.argv[1] == "go":
        go(sys.argv[2], sys.argv[3])
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
